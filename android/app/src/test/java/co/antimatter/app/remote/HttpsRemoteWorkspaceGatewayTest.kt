/** Real sockets, pin validation, wire JSON and saved credentials, with no Android framework mocks. */
class HttpsRemoteWorkspaceGatewayTest {
    private lateinit var server: HttpsServer
    private val executor = Executors.newCachedThreadPool()
    private val requests = CopyOnWriteArrayList<ReceivedRequest>()
    private val store = MemoryCredentials()
    private var pairingStatus = 201
    private var pairingBody: String? = null
    @Volatile private var blockedPath: String? = null
    @Volatile private var blockedAuthorization: String? = null
    @Volatile private var bootstrapStatus: Int = 200
    private val requestStarted = CountDownLatch(1)
    private val releaseResponse = CountDownLatch(1)
    private val secret = "a".repeat(43)
    // Match base64url identities generated by the desktop, including non-alphanumeric prefixes.
    private val hostId = "_desktop-host"
    private val workspaceId = "-workspace"
    private val deviceId = "_phone-device"
    private val token = "am1.$deviceId.${"b".repeat(43)}"
    private val endpoint get() = "https://127.0.0.1:${server.address.port}"

    @Before
    fun startHost() {
        server = HttpsServer.create(InetSocketAddress("127.0.0.1", 0), 0).apply {
            httpsConfigurator = HttpsConfigurator(serverTls)
            executor = this@HttpsRemoteWorkspaceGatewayTest.executor
            createContext("/") { exchange ->
                val body = exchange.requestBody.use { it.readBytes().toString(Charsets.UTF_8) }
                requests.add(ReceivedRequest(
                    exchange.requestURI.path,
                    exchange.requestHeaders.getFirst("Authorization"),
                    body,
                ))
                if (exchange.requestURI.path == blockedPath &&
                    (blockedAuthorization == null || exchange.requestHeaders.getFirst("Authorization") == blockedAuthorization)) {
                    requestStarted.countDown()
                    check(releaseResponse.await(5, TimeUnit.SECONDS)) { "Test did not release its response." }
                }
                val (status, response) = when (exchange.requestURI.path) {
                    "/v1/pair" -> pairingStatus to (pairingBody ?: pairedResponse())
                    "/v1/bootstrap" -> bootstrapStatus to bootstrapResponse()
                    "/v1/events" -> 200 to """{"kind":"events","events":[{"workspaceId":"$workspaceId",
                        "cursor":{"epoch":"_epoch","sequence":1},
                        "event":{"kind":"catalog.changed","revision":"1"}}]}"""
                    "/v1/commands" -> 202 to JSONObject().put("commandId", JSONObject(body).getString("commandId"))
                        .put("disposition", "accepted").toString()
                    else -> 404 to "{}"
                }
                val bytes = response.toByteArray()
                exchange.responseHeaders.add("Content-Type", "application/json")
                exchange.sendResponseHeaders(status, bytes.size.toLong())
                exchange.responseBody.use { it.write(bytes) }
                exchange.close()
            }
            start()
        }
    }

    @After
    fun stopHost() {
        releaseResponse.countDown()
        server.stop(0)
        executor.shutdownNow()
    }

    @Test
    fun `scan offer exchanges pinned HTTPS and saved credential reconnects after process restart`() = runBlocking {
        val gateway = gateway()
        val paired = gateway.pair(offer(), pairRequest()).getOrThrow()

        assertEquals(hostId, paired.host.id)
        assertEquals(workspaceId, paired.workspaceId)
        assertEquals(deviceId, paired.credential.deviceId)
        assertEquals("Pair $secret", requests.first().authorization)
        val sent = JSONObject(requests.first().body)
        assertEquals("-offer", sent.getString("offerId"))
        assertEquals("Test phone", sent.getString("deviceName"))
        assertEquals(1, sent.getJSONObject("protocol").getInt("major"))

        val saved = store.load(hostId).getOrThrow()!!
        assertEquals("Development computer", saved.endpoint.name)
        assertEquals(endpoint, saved.endpoint.baseUrl)
        assertEquals(token, saved.credential.bearerToken)
        assertEquals(pin, saved.credential.certificatePin?.value)
        assertEquals(hostId, gateway.snapshot(hostId).getOrThrow().host.id)

        // A fresh gateway has no in-memory sessions; encrypted persistence supplies everything.
        val restartedGateway = gateway()
        val restored = restartedGateway.connect(saved.endpoint, saved.credential).getOrThrow()
        assertEquals(hostId, restored.id)
        assertEquals(hostId, restartedGateway.snapshot(hostId).getOrThrow().host.id)
        assertTrue(requests.drop(1).all { it.authorization == "Bearer $token" })
    }

    @Test
    fun `wrong certificate pin sends no pairing bearer and saves no credential`() = runBlocking {
        val wrongPin = "sha256/" + Base64.getEncoder().encodeToString(ByteArray(32))
        val result = gateway().pair(offer(certificatePin = wrongPin), pairRequest())

        assertEquals(RemoteFailureCode.TLS_PIN_MISMATCH, (result.exceptionOrNull() as RemoteWorkspaceException).code)
        assertTrue(requests.isEmpty())
        assertTrue(store.list().getOrThrow().isEmpty())
    }

    @Test
    fun `expired or consumed offer tells the user to generate another code`() = runBlocking {
        for (status in listOf(401, 410)) {
            pairingStatus = status
            pairingBody = """{"error":{"code":"PAIRING_OFFER_INVALID","message":"Offer unavailable."}}"""
            val error = gateway().pair(offer(), pairRequest()).exceptionOrNull() as RemoteWorkspaceException
            assertEquals(RemoteFailureCode.AUTHENTICATION, error.code)
            assertEquals(status, error.httpStatus)
            assertTrue(error.message.contains("new QR code"))
            assertFalse(error.retryable)
        }
        assertTrue(store.list().getOrThrow().isEmpty())
    }

    @Test
    fun `local expiry is distinguished from an invalid host response before opening a socket`() = runBlocking {
        val expiredOffer = offer(expires = 2_000L, now = 1_000L)
        val error = gateway().pair(expiredOffer, pairRequest()).exceptionOrNull() as RemoteWorkspaceException
        assertEquals(RemoteFailureCode.AUTHENTICATION, error.code)
        assertTrue(error.message.contains("expired"))
        assertTrue(requests.isEmpty())
    }

    @Test
    fun `credential save failure reports accepted pairing without activating an unsaved session`() = runBlocking {
        store.saveFailure = IllegalStateException("disk full")
        val gateway = gateway()
        val error = gateway.pair(offer(), pairRequest()).exceptionOrNull() as RemoteWorkspaceException

        assertEquals(RemoteFailureCode.INTERNAL, error.code)
        assertTrue(error.message.contains("computer accepted pairing"))
        assertTrue(error.message.contains("could not save"))
        assertTrue(store.list().getOrThrow().isEmpty())
        val snapshotFailure = gateway.snapshot(hostId).exceptionOrNull() as RemoteWorkspaceException
        assertEquals(RemoteFailureCode.AUTHENTICATION, snapshotFailure.code)
        assertEquals(1, requests.size)
    }

    @Test
    fun `paired response must retain the scanned host identity`() = runBlocking {
        pairingBody = JSONObject(pairedResponse()).apply {
            getJSONObject("host").put("id", "other-host")
        }.toString()
        val error = gateway().pair(offer(), pairRequest()).exceptionOrNull() as RemoteWorkspaceException
        assertEquals(RemoteFailureCode.MALFORMED_RESPONSE, error.code)
        assertTrue(store.list().getOrThrow().isEmpty())
    }

    @Test
    fun `cancellation is not converted into a saved connection error`() = runBlocking {
        store.saveFailure = CancellationException("test cancellation")
        var canceled = false
        try {
            gateway().pair(offer(), pairRequest())
        } catch (_: CancellationException) {
            canceled = true
        }
        assertTrue(canceled)
        assertTrue(store.list().getOrThrow().isEmpty())
    }

    @Test
    fun `canceled restore does not overwrite credential or session after its HTTP response arrives`() = runBlocking {
        val gateway = gateway()
        val paired = gateway.pair(offer(), pairRequest()).getOrThrow()
        // The old opaque display name triggers a cosmetic save if the canceled restore is applied.
        val oldEndpoint = WorkspaceEndpoint.parse(hostId, endpoint).getOrThrow()
        val oldCredential = WorkspaceCredential.create(
            "old".repeat(24), deviceId, workspaceId, paired.credential.certificatePin,
        ).getOrThrow()
        blockedPath = "/v1/bootstrap"
        val restore = async(Dispatchers.Default) { gateway.connect(oldEndpoint, oldCredential) }
        assertTrue(requestStarted.await(5, TimeUnit.SECONDS))
        restore.cancel()
        releaseResponse.countDown()
        restore.join()

        assertEquals(token, store.load(hostId).getOrThrow()?.credential?.bearerToken)
        blockedPath = null
        gateway.snapshot(hostId).getOrThrow()
        assertEquals("Bearer $token", requests.last().authorization)
    }

    @Test
    fun `forget clears saved credential and active session even if revocation fails`() = runBlocking {
        val gateway = gateway()
        gateway.pair(offer(), pairRequest()).getOrThrow()
        // The fixture deliberately has no DELETE session route and returns a failure.
        assertTrue(gateway.disconnect(hostId).isFailure)
        assertTrue(store.list().getOrThrow().isEmpty())
        val error = gateway.snapshot(hostId).exceptionOrNull() as RemoteWorkspaceException
        assertEquals(RemoteFailureCode.AUTHENTICATION, error.code)
        assertEquals(2, requests.size)
    }

    @Test
    fun `expired credential or missing pin requests pairing without sending a bearer`() = runBlocking {
        for (credential in listOf(
            WorkspaceCredential.create(token).getOrThrow(),
            WorkspaceCredential.create(token, certificatePin = CertificatePin.parse(pin).getOrThrow(), expiresAtMillis = 1).getOrThrow(),
        )) {
            val error = gateway().connect(offer().endpoint, credential).exceptionOrNull() as RemoteWorkspaceException
            assertEquals(RemoteFailureCode.AUTHENTICATION, error.code)
        }
        assertTrue(requests.isEmpty())
    }

    @Test
    fun `failure to refresh a saved computer name does not block a valid connection`() = runBlocking {
        val gateway = gateway()
        val paired = gateway.pair(offer(), pairRequest()).getOrThrow()
        store.saveFailure = IllegalStateException("storage temporarily unavailable")
        val host = gateway().connect(offer().endpoint, paired.credential).getOrThrow()
        assertEquals(hostId, host.id)
        assertEquals(token, store.load(hostId).getOrThrow()?.credential?.bearerToken)
    }

    @Test
    fun `temporary TLS handshake interruption retries without requesting new pairing`() {
        val interrupted = SSLHandshakeException("Remote host terminated the handshake").apply {
            initCause(java.io.EOFException("Connection closed"))
        }
        val failure = gateway().mapFailure(interrupted) as RemoteWorkspaceException
        assertEquals(RemoteFailureCode.NETWORK, failure.code)
        assertTrue(failure.retryable)
        val changedPin = SSLHandshakeException("Certificate rejected").apply {
            initCause(CertificateException("Pin changed"))
        }
        val rejected = gateway().mapFailure(changedPin) as RemoteWorkspaceException
        assertEquals(RemoteFailureCode.TLS_PIN_MISMATCH, rejected.code)
        assertFalse(rejected.retryable)
    }

    @Test
    fun `cancelling a blocked response closes its socket before the network timeout`() = runBlocking {
        val gateway = HttpsRemoteWorkspaceGateway(store, requestTimeoutMillis = 30_000)
        gateway.pair(offer(), pairRequest()).getOrThrow()
        blockedPath = "/v1/bootstrap"
        val request = async(Dispatchers.Default) { gateway.snapshot(hostId) }
        assertTrue(requestStarted.await(5, TimeUnit.SECONDS))
        try {
            request.cancel()
            // The host deliberately withholds its response. Cancellation must release the
            // reconnect job while preserving the existing pairing credential.
            withTimeout(1_500) { request.join() }
            assertEquals(token, store.load(hostId).getOrThrow()?.credential?.bearerToken)
        } finally {
            releaseResponse.countDown()
        }
    }

    @Test
    fun `late restore cannot overwrite a newer connection or its credential`() = runBlocking {
        val gateway = gateway()
        val paired = gateway.pair(offer(), pairRequest()).getOrThrow()
        val old = WorkspaceCredential.create("old".repeat(24), deviceId, workspaceId, paired.credential.certificatePin).getOrThrow()
        blockedPath = "/v1/bootstrap"
        blockedAuthorization = "Bearer ${old.bearerToken}"
        val restore = async(Dispatchers.Default) { gateway.connect(offer().endpoint, old) }
        assertTrue(requestStarted.await(5, TimeUnit.SECONDS))
        try {
            gateway.connect(offer().endpoint, paired.credential).getOrThrow()
            releaseResponse.countDown()
            assertTrue(runCatching { withTimeout(1_500) { restore.await() } }.exceptionOrNull() is CancellationException)
            assertTrue(restore.isCancelled)
            assertEquals(token, store.load(hostId).getOrThrow()?.credential?.bearerToken)
            gateway.snapshot(hostId).getOrThrow()
            assertEquals("Bearer $token", requests.last().authorization)
        } finally {
            releaseResponse.countDown()
            restore.cancel()
        }
    }

    @Test
    fun `forget during process restart bootstrap cannot resurrect saved connection`() = runBlocking {
        gateway().pair(offer(), pairRequest()).getOrThrow()
        val saved = store.load(hostId).getOrThrow()!!
        val restarted = gateway()
        blockedPath = "/v1/bootstrap"
        val restore = async(Dispatchers.Default) { restarted.connect(saved.endpoint, saved.credential) }
        assertTrue(requestStarted.await(5, TimeUnit.SECONDS))
        try {
            restarted.disconnect(hostId).getOrThrow()
            releaseResponse.countDown()
            assertTrue(runCatching { withTimeout(1_500) { restore.await() } }.exceptionOrNull() is CancellationException)
            assertTrue(restore.isCancelled)
            assertTrue(store.list().getOrThrow().isEmpty())
            assertEquals(RemoteFailureCode.AUTHENTICATION,
                (restarted.snapshot(hostId).exceptionOrNull() as RemoteWorkspaceException).code)
        } finally {
            releaseResponse.countDown()
            restore.cancel()
        }
    }

    @Test
    fun `old event poll cannot deliver frames into a replacement session`() = runBlocking {
        val gateway = gateway()
        val paired = gateway.pair(offer(), pairRequest()).getOrThrow()
        blockedPath = "/v1/events"
        val poll = async(Dispatchers.Default) { gateway.events(hostId, EventCursor("_epoch", 0)).first() }
        assertTrue(requestStarted.await(5, TimeUnit.SECONDS))
        try {
            gateway.connect(offer().endpoint, paired.credential).getOrThrow()
            releaseResponse.countDown()
            assertTrue(runCatching { withTimeout(1_500) { poll.await() } }.exceptionOrNull() is CancellationException)
            assertTrue(poll.isCancelled)
            assertEquals(1, requests.count { it.path == "/v1/events" })
            assertTrue(gateway.events(hostId, EventCursor("_epoch", 0)).first() is WorkspaceStreamFrame.Event)
        } finally {
            releaseResponse.countDown()
            poll.cancel()
        }
    }

    @Test
    fun `old snapshot failure cannot report replacement session offline`() = runBlocking {
        val gateway = gateway()
        val paired = gateway.pair(offer(), pairRequest()).getOrThrow()
        blockedPath = "/v1/bootstrap"
        val snapshot = async(Dispatchers.Default) { gateway.snapshot(hostId) }
        assertTrue(requestStarted.await(5, TimeUnit.SECONDS))
        try {
            blockedPath = null
            gateway.connect(offer().endpoint, paired.credential).getOrThrow()
            bootstrapStatus = 503
            releaseResponse.countDown()
            assertTrue(runCatching { withTimeout(1_500) { snapshot.await() } }.exceptionOrNull() is CancellationException)
            assertTrue(snapshot.isCancelled)
            bootstrapStatus = 200
            gateway.snapshot(hostId).getOrThrow()
            Unit
        } finally {
            releaseResponse.countDown()
            snapshot.cancel()
        }
    }

    @Test
    fun `cancel command uses independent connection while event poll is waiting`() = runBlocking {
        val gateway = gateway()
        gateway.pair(offer(), pairRequest()).getOrThrow()
        blockedPath = "/v1/events"
        val poll = async(Dispatchers.Default) { gateway.events(hostId, EventCursor("_epoch", 0)).first() }
        assertTrue(requestStarted.await(5, TimeUnit.SECONDS))
        try {
            val command = WorkspaceCommand.CancelTurn(hostId, "project", "cancel-command", "thread", "run")
            assertEquals(command.commandId, withTimeout(1_500) { gateway.send(command).getOrThrow() }.commandId)
            assertFalse(poll.isCompleted)
            assertEquals(1, requests.count { it.path == "/v1/commands" })
        } finally {
            poll.cancel()
            releaseResponse.countDown()
            poll.join()
        }
    }

    @Test
    fun `late failed bootstrap is canceled after a newer connection succeeds`() = runBlocking {
        val gateway = gateway()
        val paired = gateway.pair(offer(), pairRequest()).getOrThrow()
        val old = WorkspaceCredential.create("old".repeat(24), deviceId, workspaceId, paired.credential.certificatePin).getOrThrow()
        blockedPath = "/v1/bootstrap"
        blockedAuthorization = "Bearer ${old.bearerToken}"
        val restore = async(Dispatchers.Default) { gateway.connect(offer().endpoint, old) }
        assertTrue(requestStarted.await(5, TimeUnit.SECONDS))
        try {
            gateway.connect(offer().endpoint, paired.credential).getOrThrow()
            bootstrapStatus = 503
            releaseResponse.countDown()
            assertTrue(runCatching { withTimeout(1_500) { restore.await() } }.exceptionOrNull() is CancellationException)
            assertTrue(restore.isCancelled)
            bootstrapStatus = 200
            assertEquals(hostId, gateway.snapshot(hostId).getOrThrow().host.id)
        } finally {
            releaseResponse.countDown()
            restore.cancel()
        }
    }

    private fun gateway() = HttpsRemoteWorkspaceGateway(store, connectTimeoutMillis = 2_000, requestTimeoutMillis = 2_000)

    private fun pairRequest() = PairingRequest("Test phone", "0.1.0-test", setOf(WorkspaceCapability.CHAT))

    private fun offer(
        certificatePin: String = pin,
        expires: Long = System.currentTimeMillis() + 120_000,
        now: Long = System.currentTimeMillis(),
    ): PairingOffer {
        val fields = linkedMapOf(
            "endpoint" to endpoint, "host" to hostId, "offer" to "-offer", "secret" to secret,
            "pin" to certificatePin, "expires" to expires.toString(),
        )
        val query = fields.entries.joinToString("&") { (key, value) ->
            "$key=${URLEncoder.encode(value, Charsets.UTF_8.name())}"
        }
        return PairingOffer.parse("ANTIMATTER-PAIRING-V1?$query", now).getOrThrow()
    }

    private fun pairedResponse() = JSONObject()
        .put("protocol", JSONObject().put("major", 1).put("minor", 0))
        .put("host", JSONObject().put("id", hostId).put("name", "Development computer").put("certificatePin", pin))
        .put("workspace", JSONObject().put("id", workspaceId))
        .put("device", JSONObject().put("id", deviceId).put("capabilities", org.json.JSONArray(listOf("chat"))))
        .put("credential", JSONObject().put("scheme", "Bearer").put("token", token))
        .toString()

    private fun bootstrapResponse() = """
        {"protocolVersion":1,"host":{"id":"$hostId","name":"Development computer"},
        "workspace":{"id":"$workspaceId"},"capabilities":["chat"],
        "cursor":{"epoch":"_epoch","sequence":0}}
    """.trimIndent()

    private data class ReceivedRequest(val path: String, val authorization: String?, val body: String)

    private class MemoryCredentials : WorkspaceCredentialStore {
        private val values = mutableMapOf<String, StoredHostCredential>()
        var saveFailure: Exception? = null
        override fun save(value: StoredHostCredential): Result<Unit> = runCatching {
            saveFailure?.let { throw it }
            values[value.hostId] = value
        }
        override fun load(hostId: String) = Result.success(values[hostId])
        override fun list() = Result.success(values.values.toList())
        override fun remove(hostId: String) = Result.success(Unit).also { values.remove(hostId) }
    }

    companion object {
        private lateinit var serverTls: SSLContext
        private lateinit var pin: String

        @BeforeClass
        @JvmStatic
        fun createPinnedTestCertificate() {
            val directory = Files.createTempDirectory("antimatter-pairing-tls-")
            val keyFile = directory.resolve("test.p12")
            try {
                val executable = if (System.getProperty("os.name").orEmpty().startsWith("Windows")) "keytool.exe" else "keytool"
                val process = ProcessBuilder(
                    Path.of(System.getProperty("java.home"), "bin", executable).toString(),
                    "-genkeypair", "-alias", "host", "-keyalg", "EC", "-groupname", "secp256r1",
                    "-dname", "CN=Antimatter Remote Test", "-validity", "2", "-storetype", "PKCS12",
                    "-keystore", keyFile.toString(), "-storepass", "test-fixture-only", "-noprompt",
                ).redirectErrorStream(true).start()
                check(process.waitFor(30, TimeUnit.SECONDS)) { "Timed out creating the test TLS certificate." }
                check(process.exitValue() == 0) { process.inputStream.readBytes().toString(Charsets.UTF_8) }
                val keyStore = KeyStore.getInstance("PKCS12").apply {
                    Files.newInputStream(keyFile).use { load(it, "test-fixture-only".toCharArray()) }
                }
                val managers = KeyManagerFactory.getInstance(KeyManagerFactory.getDefaultAlgorithm()).apply {
                    init(keyStore, "test-fixture-only".toCharArray())
                }
                serverTls = SSLContext.getInstance("TLS").apply { init(managers.keyManagers, null, null) }
                pin = "sha256/" + Base64.getEncoder().encodeToString(
                    MessageDigest.getInstance("SHA-256").digest(keyStore.getCertificate("host").encoded),
                )
            } finally {
                Files.deleteIfExists(keyFile)
                Files.deleteIfExists(directory)
            }
        }
    }
}
