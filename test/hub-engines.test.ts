test('a qwen3moe download goes on the GPU source by path at once and onto the bundled engine after an idle restart', async (t) => {
  const root = scratch(t);
  const path = join(root, 'hub', 'q4.gguf');
  mkdirSync(join(path, '..'), { recursive: true });
  writeFileSync(path, 'GGUF');
  const record = downloadRecord({
    id: 'r1',
    path,
    modelId: 'qwen3-coder-30b-a3b-instruct-q4_k_m',
    quantization: 'Q4_K_M',
    contextLength: 262144,
    state: 'downloading',
  });
  const { registrar, sources, calls, deps } = harness(root, { records: [record], busyPolls: 2 });

  assert.equal(registrar.prepareStart(), null, 'nothing is ready yet, so the base starts untouched');
  record.state = 'ready';
  assert.equal(registrar.prepareStart(), deps.overlayPath);
  await registrar.register(record);

  const gpu = sources.find((source) => source.id === 'gpu')!;
  assert.deepEqual(gpu.models.at(-1), {
    id: path,
    name: 'qwen3-coder-30b-a3b-instruct-q4_k_m',
    architecture: 'qwen3moe',
    quantization: 'Q4_K_M',
    contextWindow: 131072,
  });
  assert.equal(sources.find((source) => source.id === 'cloud')!.models.length, 0, 'remote sources cannot load a local path');

  // Let the restart loop run to completion.
  await new Promise((resolve) => setTimeout(resolve, 20));
  assert.equal(calls.restarts, 1, 'one restart, after the in-flight request finished');
  assert.ok(calls.busyChecks >= 3);
  assert.equal(existsSync(deps.overlayPath), true);
  assert.deepEqual(
    sources.find((source) => source.id === 'bundled')!.models.find((model) => model.id === 'qwen3-coder-30b-a3b-instruct-q4_k_m'),
    {
      id: 'qwen3-coder-30b-a3b-instruct-q4_k_m',
      name: 'qwen3-coder-30b-a3b-instruct-q4_k_m',
      architecture: 'qwen3moe',
      quantization: 'Q4_K_M',
      contextWindow: 262144,
    }
  );
  assert.deepEqual(
    record.registrations.map((entry) => [entry.target, entry.sourceId, entry.status, entry.modelId]),
    [
      ['bundled', 'bundled', 'registered', 'qwen3-coder-30b-a3b-instruct-q4_k_m'],
      ['external', 'gpu', 'registered', path],
    ]
  );
  assert.ok(calls.changed >= 2);

  // Startup: the server already lists what the overlay holds, so reconciling must not restart it.
  await registrar.reconcile();
  await new Promise((resolve) => setTimeout(resolve, 20));
  assert.equal(calls.restarts, 1);

  // Removing it takes it off the GPU source and restarts the bundled engine without it.
  record.state = 'failed';
  registrar.unregister({ ...record, state: 'ready' });
  await new Promise((resolve) => setTimeout(resolve, 20));
  assert.equal(sources.find((source) => source.id === 'gpu')!.models.some((model) => model.id === path), false);
  assert.equal(calls.restarts, 2);
  assert.equal(sources.find((source) => source.id === 'bundled')!.models.some((model) => model.id !== 'qwen3-coder-30b'), false);
});

