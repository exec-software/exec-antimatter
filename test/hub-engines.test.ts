const BASE_YAML = `# hand-tuned, with comments that must never be lost from this file
memory_budget_bytes: 14000000000
runtime_headroom_bytes: 4294967296

models:
  - id: qwen3-coder-30b
    path: models-local/qwen3-coder-30b/Qwen3-Coder-30B-A3B-Instruct-Q8_0.gguf
    weight_mode: streaming
    fit_policy: exact
    allow_unsafe_storage: false
    pinned_cache_bytes: 4000000000
    demand_cache_bytes: 6000000000
    prefetch_bytes: 1073741824
    prefetch_queue_depth: 8
    prefetch_workers: 4
    near_miss_prefetch: false
`;

function scratch(t: { after(fn: () => unknown): void }) {
  const root = mkdtempSync(join(tmpdir(), 'antimatter-engines-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  return root;
}

test('the overlay keeps the base, absolutizes its paths, copies its dials, and never duplicates a file', (t) => {
  const root = scratch(t);
  const baseDir = join(root, 'beholdd');
  const baseModel = join(baseDir, 'models-local/qwen3-coder-30b/Qwen3-Coder-30B-A3B-Instruct-Q8_0.gguf');
  mkdirSync(join(baseModel, '..'), { recursive: true });
  writeFileSync(baseModel, 'GGUF');
  // The Hub cache reaches the same bytes through a snapshot symlink.
  const snapshot = join(root, 'hub', 'snapshot-link.gguf');
  mkdirSync(join(snapshot, '..'), { recursive: true });
  symlinkSync(baseModel, snapshot);

  const overlay = buildOverlay(BASE_YAML, baseDir, [
    { id: 'qwen3-coder-30b-a3b-instruct-q4_k_m', path: '/models/q4.gguf' },
    { id: 'qwen3-coder-30b', path: '/models/other-q8.gguf' },
    { id: 'something-else', path: snapshot },
  ]);

  const models = overlay.config.models as Record<string, unknown>[];
  assert.equal(overlay.config.memory_budget_bytes, 14000000000);
  assert.equal(models[0].path, baseModel, 'relative base paths resolve beside the base file');
  assert.deepEqual(
    models.map((model) => model.id),
    ['qwen3-coder-30b', 'qwen3-coder-30b-a3b-instruct-q4_k_m', 'qwen3-coder-30b-2']
  );
  const { id: _id, path: _path, ...dials } = models[0];
  assert.deepEqual({ ...models[1], id: undefined, path: undefined }, { ...dials, id: undefined, path: undefined });
  assert.equal(overlay.ids.get(snapshot), 'qwen3-coder-30b', 'a file the base already serves keeps its base id');
  assert.ok(overlay.inBase.has(snapshot));
  assert.equal(overlay.ids.get('/models/other-q8.gguf'), 'qwen3-coder-30b-2');

  const rendered = renderOverlay(overlay.config, join(baseDir, 'config.v2.yaml'));
  assert.match(rendered, /^# Generated by Antimatter/);
  assert.deepEqual(load(rendered), overlay.config);

  const fresh = buildOverlay(null, root, [{ id: 'a', path: '/m/a.gguf' }]);
  assert.deepEqual((fresh.config.models as Record<string, unknown>[])[0], { ...STREAMING_PROFILE, id: 'a', path: '/m/a.gguf' });
  assert.throws(() => buildOverlay('- just\n- a list\n', root, []), /not a YAML mapping/);
});

test('path-capable engines, server context, and refreshed model lists', () => {
  assert.equal(acceptsPathModels({ status: 'ok', engine: 'subprocess', loaded: [] }), true);
  assert.equal(acceptsPathModels({ status: 'ok' }), false);
  assert.equal(acceptsPathModels(null), false);

  assert.equal(
    typicalContext([
      { id: 'a', name: 'a', contextWindow: 131072 },
      { id: 'b', name: 'b', contextWindow: 131072 },
      { id: 'c', name: 'c', contextWindow: 8192 },
      { id: 'd', name: 'd' },
    ]),
    131072
  );

  const source: InferenceSource = {
    id: 'gpu',
    name: 'beholdd GPU',
    kind: 'beholdd',
    apiKey: '',
    baseUrl: 'http://127.0.0.1:6767/v1',
    supportsStreaming: true,
    createdAt: 1,
    models: [{ id: 'qwen3-coder-30b', name: 'qwen3-coder-30b', contextWindow: 131072 }],
  };
  const record = downloadRecord({
    path: '/hub/tiny.gguf',
    modelId: 'tiny-q8_0',
    quantization: 'Q8_0',
    contextLength: 40960,
  });
  record.registrations = [registration({ target: 'external', sourceId: 'gpu', modelId: '/hub/tiny.gguf' })];

  const merged = withRegisteredModels(source, [record]);
  assert.deepEqual(merged.models.at(-1), {
    id: '/hub/tiny.gguf',
    name: 'tiny-q8_0',
    architecture: 'qwen3moe',
    quantization: 'Q8_0',
    contextWindow: 40960,
  });
  assert.equal(withRegisteredModels(merged, [record]).models.length, 2, 'merging twice adds nothing');
  assert.equal(withRegisteredModels({ ...source, id: 'other' }, [record]).models.length, 1);
});

function downloadRecord(patch: Partial<DownloadRecord> = {}): DownloadRecord {
  return {
    id: patch.modelId ?? 'record',
    repoId: 'acme/Model-GGUF',
    revision: 'a'.repeat(40),
    variantKey: 'model.gguf',
    label: 'Q8_0',
    role: 'model',
    files: [],
    bytesTotal: 1,
    bytesDone: 1,
    state: 'ready',
    phase: null,
    error: null,
    root: '/hub',
    createdAt: 1,
    startedAt: 1,
    finishedAt: 2,
    path: '/hub/model.gguf',
    architecture: 'qwen3moe',
    contextLength: 262144,
    modelId: 'model-q8_0',
    registrations: [],
    ...patch,
  };
}

function registration(patch: Partial<Registration>): Registration {
  return { target: 'bundled', sourceId: null, sourceName: 'x', status: 'registered', modelId: null, detail: null, at: 0, ...patch };
}

test('registered download decoration preserves only the existing model execution cap', () => {
  for (const maxEvaluatedTokens of [128, null, undefined]) {
    const current: Model = {
      id: 'served', name: 'Server model', contextWindow: 131072,
      ...(maxEvaluatedTokens !== undefined ? { maxEvaluatedTokens } : {}),
    };
    const source: InferenceSource = {
      id: 'local', name: 'Beholdd', kind: 'beholdd', apiKey: '',
      baseUrl: 'http://127.0.0.1:6768/v1', supportsStreaming: true, createdAt: 1,
      models: [current],
    };
    const existing = downloadRecord({
      path: '/hub/served.gguf', modelId: 'downloaded', architecture: 'qwen3', quantization: 'Q8_0',
      registrations: [registration({ sourceId: source.id, modelId: current.id })],
    });
    const unrelated = downloadRecord({
      path: '/hub/other.gguf', modelId: 'other',
      registrations: [registration({ target: 'external', sourceId: source.id, modelId: '/hub/other.gguf' })],
    });

    const decorated = withRegisteredModels(source, [existing, unrelated]);
    assert.notEqual(decorated.models[0], current, 'download metadata must exercise reconstruction');
    assert.equal(decorated.models[0].architecture, 'qwen3');
    assert.equal(decorated.models[0].quantization, 'Q8_0');
    assert.equal(decorated.models[0].maxEvaluatedTokens, maxEvaluatedTokens);
    assert.equal(Object.hasOwn(decorated.models[0], 'maxEvaluatedTokens'), maxEvaluatedTokens !== undefined);
    assert.equal(Object.hasOwn(decorated.models[1], 'maxEvaluatedTokens'), false,
      'a new path model must not inherit an observed sibling cap');
    assert.equal(current.architecture, undefined, 'source input remains unchanged');
    assert.equal(current.maxEvaluatedTokens, maxEvaluatedTokens);
    assert.equal(withRegisteredModels(decorated, [existing, unrelated]), decorated,
      'unchanged repeated decoration preserves source identity');
  }
});

function harness(root: string, options: { records: DownloadRecord[]; busyPolls?: number; ownership?: 'app' | 'external'; health?: unknown }) {
  const basePath = join(root, 'config.v2.yaml');
  writeFileSync(basePath, BASE_YAML);
  const sources: InferenceSource[] = [
    { id: 'bundled', name: 'beholdd', kind: 'beholdd', apiKey: '', baseUrl: 'http://127.0.0.1:6768/v1', supportsStreaming: true, createdAt: 1, models: [{ id: 'qwen3-coder-30b', name: 'qwen3-coder-30b' }] },
    { id: 'gpu', name: 'beholdd GPU', kind: 'beholdd', apiKey: 'k', baseUrl: 'http://127.0.0.1:6767/v1', supportsStreaming: true, createdAt: 2, models: [{ id: 'glm', name: 'glm', contextWindow: 131072 }] },
    { id: 'cloud', name: 'OpenAI', kind: 'openai', apiKey: 'k', baseUrl: 'https://api.openai.com/v1', supportsStreaming: true, createdAt: 3, models: [] },
  ];
  const records = options.records;
  let served: Model[] = [{ id: 'qwen3-coder-30b', name: 'qwen3-coder-30b' }];
  let busyPolls = options.busyPolls ?? 0;
  const calls = { restarts: 0, changed: 0, busyChecks: 0, logs: [] as string[] };
  let clock = 1_000;
  let registrar: Registrar | null = null;

  const deps: RegistrarDeps = {
    overlayPath: join(root, 'userData', 'beholdd', 'config.hub.yaml'),
    basePath: () => basePath,
    sources: () => sources,
    saveSource: (source) => {
      const index = sources.findIndex((entry) => entry.id === source.id);
      if (index === -1) sources.push(source);
      else sources[index] = source;
    },
    bundledPort: () => 6768,
    bundledStatus: async () => ({ running: true, ready: true, ownership: options.ownership ?? 'app', host: '127.0.0.1', port: 6768 }),
    restartBundled: async () => {
      calls.restarts += 1;
      // As beholdd.ts does on every start: prepare the overlay, or fall back to the base, and serve
      // exactly what that file holds.
      const config = registrar!.prepareStart() ?? basePath;
      const written = load(readFileSync(config, 'utf8')) as { models: { id: string }[] };
      served = written.models.map((model) => ({ id: model.id, name: model.id }));
      return { ready: true };
    },
    sourceBusy: (id) => {
      calls.busyChecks += 1;
      return id === 'bundled' && busyPolls-- > 0;
    },
    probe: async () => ({ ok: true, models: served }),
    health: async (baseUrl) => (baseUrl.includes('6767') ? (options.health ?? { status: 'ok', engine: 'subprocess' }) : { status: 'ok' }),
    records: () => records,
    setRegistrations: (id, next) => {
      const record = records.find((entry) => entry.id === id)!;
      record.registrations = next;
    },
    changed: () => (calls.changed += 1),
    log: (message) => calls.logs.push(message),
    sleep: async () => undefined,
    now: () => (clock += 1),
  };
  registrar = new Registrar(deps);
  return { registrar, sources, calls, deps, records };
}

test('startup inspection renders an eligible overlay without creating files or changing models', (t) => {
  const root = scratch(t);
  const path = join(root, 'download.gguf');
  writeFileSync(path, 'GGUF');
  const { registrar, sources, calls, deps, records } = harness(root, { records: [downloadRecord({ path })] });
  const before = JSON.stringify({ sources, calls, records });
  for (let i = 0; i < 3; i++) assert.equal(registrar.canPrepareStart(), true);
  assert.equal(existsSync(join(root, 'userData')), false, 'inspection must not create the overlay directory');
  assert.equal(readFileSync(deps.basePath(), 'utf8'), BASE_YAML, 'the base configuration stays untouched');
  assert.equal(JSON.stringify({ sources, calls, records }), before);

  // The same rendering decision is used when the first request actually starts the engine.
  assert.equal(registrar.prepareStart(), deps.overlayPath);
  const written = load(readFileSync(deps.overlayPath, 'utf8')) as { models: { id: string }[] };
  assert.ok(written.models.some((model) => model.id === records[0].modelId));
});

