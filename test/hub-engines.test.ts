test('startup inspection shares eligibility and base reuse decisions with preparation', (t) => {
  const root = scratch(t);
  const path = join(root, 'download.gguf');
  writeFileSync(path, 'GGUF');
  const record = downloadRecord({ path });
  const { registrar, deps } = harness(root, { records: [record] });
  for (const patch of [{ state: 'downloading' as const }, { architecture: 'qwen2' }, { fileType: 139 }, { path: join(root, 'missing.gguf') }]) {
    Object.assign(record, downloadRecord({ path, fileType: undefined }), patch);
    assert.equal(registrar.canPrepareStart(), false);
    assert.equal(registrar.prepareStart(), null);
  }
  Object.assign(record, downloadRecord({ path, fileType: undefined }));
  assert.equal(registrar.canPrepareStart(), true);
  writeFileSync(deps.basePath(), `models:\n  - id: already-served\n    path: ${path}\n`);
  assert.equal(registrar.canPrepareStart(), false, 'a download already named by the base needs no generated config');
  assert.equal(registrar.prepareStart(), null);
  assert.equal(existsSync(deps.overlayPath), false);
});

