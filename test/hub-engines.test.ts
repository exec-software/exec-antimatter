test('a quantization no llama.cpp build here decodes is refused by every engine, without asking a server', async (t) => {
  const root = scratch(t);
  const path = join(root, 'kimi.gguf');
  writeFileSync(path, 'GGUF');
  // Architecture the bundled engine does serve, so what refuses it is the quantization alone.
  const record = downloadRecord({ id: 'r9', path, architecture: 'qwen3moe', fileType: 139, modelId: 'kimi-iq3-k' });
  const { registrar, sources, calls } = harness(root, { records: [record] });

  await registrar.register(record);
  await new Promise((resolve) => setTimeout(resolve, 20));

  const bundled = record.registrations.find((entry) => entry.target === 'bundled')!;
  const gpu = record.registrations.find((entry) => entry.target === 'external')!;
  assert.equal(bundled.status, 'unsupported');
  assert.equal(gpu.status, 'unsupported');
  assert.match(gpu.detail!, /general\.file_type 139/);
  assert.match(bundled.detail!, /ik_llama\.cpp/);

  // Nothing registered, nothing restarted, and nothing written into the bundled configuration.
  assert.equal(sources.find((source) => source.id === 'gpu')!.models.length, 1);
  assert.equal(calls.restarts, 0);
  assert.equal(registrar.prepareStart(), null);
});

test('a model registered before its quantization was known is taken back off the source', async (t) => {
  const root = scratch(t);
  const path = join(root, 'kimi.gguf');
  writeFileSync(path, 'GGUF');
  const record = downloadRecord({ id: 'r10', path, architecture: 'qwen2', fileType: 139, modelId: 'kimi-iq3-k' });
  const { registrar, sources, calls } = harness(root, { records: [record] });

  // As an earlier build left it: already on the GPU source by path, reading as a model that works.
  const gpu = sources.find((source) => source.id === 'gpu')!;
  gpu.models = [...gpu.models, { id: path, name: 'kimi-iq3-k' }];
  const changedBefore = calls.changed;

  await registrar.register(record);
  await new Promise((resolve) => setTimeout(resolve, 20));

  assert.equal(record.registrations.find((entry) => entry.target === 'external')!.status, 'unsupported');
  assert.ok(
    !sources.find((source) => source.id === 'gpu')!.models.some((model) => model.id === path),
    'it is no longer offered'
  );
  assert.ok(calls.changed > changedBefore, 'and the source list change is announced');
});

