#!/usr/bin/env node
/** Native renderer-only setup, model library, and inference diagnostics smoke. All IPC is mocked; network and permission access are denied. */
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';

const filename = fileURLToPath(import.meta.url);
if (!process.versions.electron) {
  const { build } = await import('esbuild');
  const { default: electron } = await import('electron');
  const assets = path.resolve(process.argv[2] || 'dist-electron/renderer/assets');
  const css = (await fs.readdir(assets)).find((name) => /^main-.*\.css$/.test(name));
  assert.ok(css, 'Pass a production renderer assets directory with main CSS.');
  const output = await fs.mkdtemp('/var/tmp/antimatter-setup-models-smoke-');
  await build({ entryPoints: [path.resolve(path.dirname(filename), '../test/fixtures/setup-models-renderer.tsx')], outfile: path.join(output, 'fixture.js'), bundle: true, platform: 'browser', format: 'esm', jsx: 'automatic', define: { 'process.env.NODE_ENV': '"production"' }, loader: { '.js': 'jsx' } });
  await fs.copyFile(path.join(assets, css), path.join(output, 'fixture.css'));
  for (const name of await fs.readdir(assets)) if (/\.(woff2?|ttf)$/.test(name)) await fs.copyFile(path.join(assets, name), path.join(output, name));
  await fs.writeFile(path.join(output, 'index.html'), '<!doctype html><html><head><meta charset="UTF-8"><meta http-equiv="Content-Security-Policy" content="default-src \'none\'; script-src \'self\'; style-src \'self\' \'unsafe-inline\'; font-src \'self\'; img-src \'self\' data:; connect-src \'none\'; media-src \'none\'"><link rel="stylesheet" href="fixture.css"></head><body><div id="root"></div><script type="module" src="fixture.js"></script></body></html>');
  console.log(`Setup/models smoke output: ${output}`);
  const child = spawn(electron, ['--ozone-platform=headless', '--ozone-override-screen-size=1440,1200', filename, '--fixture', output], { stdio: 'inherit', env: { ...process.env, ELECTRON_RUN_AS_NODE: '' } });
  const deadline = setTimeout(() => { console.error('Setup/models fixture timed out; stopping only the isolated fixture.'); child.kill(); process.exitCode = 1; }, 45_000);
  child.on('error', (error) => { console.error(error); process.exitCode = 1; });
  child.on('exit', (code) => { clearTimeout(deadline); process.exitCode = code ?? 1; });
} else {
  const { app, BrowserWindow, session } = await import('electron');
  const output = process.argv[process.argv.indexOf('--fixture') + 1];
  app.setPath('userData', path.join(output, 'user-data'));
  app.commandLine.appendSwitch('disable-gpu');
  app.whenReady().then(async () => {
    const isolated = session.fromPartition(`setup-models-smoke-${process.pid}`);
    isolated.setPermissionRequestHandler((_contents, _permission, callback) => callback(false));
    isolated.setPermissionCheckHandler(() => false);
    isolated.webRequest.onBeforeRequest((details, callback) => callback({ cancel: !details.url.startsWith('file:') && !details.url.startsWith('data:') }));
    const window = new BrowserWindow({ show: false, width: 1160, height: 960, enableLargerThanScreen: true, webPreferences: { session: isolated, nodeIntegration: false, contextIsolation: true, sandbox: true, offscreen: true } });
    const failures = [];
    window.webContents.on('console-message', (event) => { if (event.level === 'error') { failures.push(event.message); console.error('Fixture renderer:', event.message); } });
    const run = (code) => window.webContents.executeJavaScript(code);
    const tick = () => run('new Promise(resolve => setTimeout(resolve, 80))');
    const click = async (label) => { await run(`(() => { const button = [...document.querySelectorAll('button')].find(item => item.checkVisibility() && item.textContent.trim() === ${JSON.stringify(label)}); if (!button || button.disabled) throw Error('Unavailable button: ' + ${JSON.stringify(label)}); button.click(); })()`); await tick(); };
    const input = async (selector, value) => { await run(`(() => { const element = document.querySelector(${JSON.stringify(selector)}); if (!element || !element.checkVisibility()) throw Error('Unavailable input'); Object.getOwnPropertyDescriptor(element instanceof HTMLTextAreaElement ? HTMLTextAreaElement.prototype : HTMLInputElement.prototype, 'value').set.call(element, ${JSON.stringify(value)}); element.dispatchEvent(new Event('input', { bubbles: true })); })()`); await tick(); };
    const select = async (selector, selected) => { await run(`(() => { const element = document.querySelector(${JSON.stringify(selector)}); if (!element || element.disabled) throw Error('Unavailable select: ' + ${JSON.stringify(selector)}); element.value = ${JSON.stringify(selected)}; element.dispatchEvent(new Event('change', { bubbles: true })); })()`); await tick(); };
    const cardClick = async (selector, label) => { await run(`(() => { const scope = document.querySelector(${JSON.stringify(selector)}); const button = [...scope.querySelectorAll('button')].find(item => item.checkVisibility() && item.textContent.trim() === ${JSON.stringify(label)}); if (!button || button.disabled) throw Error('Unavailable card action: ' + ${JSON.stringify(label)}); button.click(); })()`); await tick(); };
    const value = (selector) => run(`document.querySelector(${JSON.stringify(selector)}).value`);
    const models = () => run(`[...document.querySelectorAll('[data-model]')].map(e => e.dataset.model).sort()`);
    const profiles = () => run(`[...document.querySelectorAll('[data-profile]')].map(e => e.dataset.profile).sort()`);
    const metric = label => run(`(() => { const dt = [...document.querySelectorAll('dt')].find(e => e.textContent === ${JSON.stringify(label)}); return dt?.nextElementSibling?.textContent; })()`);
    const screenshot = async (name) => fs.writeFile(path.join(output, name), (await window.webContents.capturePage()).toPNG());
    try {
      await window.loadFile(path.join(output, 'index.html')); await tick();
      assert.equal(await value('input[placeholder="What should I call you?"]'), 'Sam');
      const dialogBackground = await run('getComputedStyle(document.querySelector("[role=dialog]")).backgroundColor');
      assert.notEqual(dialogBackground, 'rgba(0, 0, 0, 0)', 'setup dialog must have an opaque background');
      assert.notEqual(dialogBackground, 'transparent');
      await screenshot('setup-person.png');
      await input('input[placeholder="What should I call you?"]', 'Alex');
      await run('setupSmoke.fail("user")'); await click('Save and continue');
      assert.equal(await run('document.querySelector("#setup-title").textContent'), 'About you');
      assert.match(await run('document.querySelector("[role=alert]").textContent'), /Synthetic user write failure/);
      await click('Save and continue');
      assert.equal(await run('setupSmoke.state().person.name'), 'Alex');
      await input('input[placeholder="Antimatter"]', 'Nova');
      await input('textarea', 'Warm, direct, and curious. Explain tradeoffs and keep answers concise.');
      await screenshot('setup-assistant.png');
      await click('Back');
      assert.equal(await value('input[placeholder="What should I call you?"]'), 'Alex');
      await click('Save and continue');
      assert.equal(await value('input[placeholder="Antimatter"]'), 'Nova', 'assistant draft survives Back');
      await run('setupSmoke.fail("assistant")'); await click('Save and continue');
      assert.match(await run('document.querySelector("[role=alert]").textContent'), /Synthetic assistant write failure/);
      await click('Save and continue');
      assert.equal(await run('setupSmoke.state().setup.assistant.name'), 'Nova');
      assert.match(await run('setupSmoke.state().setup.assistant.personality'), /Warm, direct/);
      assert.equal(await run('document.querySelectorAll("[role=dialog] article").length'), 3);
      await screenshot('setup-workloads.png');
      await run('(() => { const body = document.querySelector("[role=dialog] > div:nth-child(2)"); body.scrollTop = body.scrollHeight; })()'); await tick();
      await screenshot('setup-workloads-bottom.png');
      window.setSize(680, 960); await tick();
      assert.ok(await run('document.documentElement.scrollWidth <= window.innerWidth'));
      await screenshot('setup-workloads-narrow.png');
      window.setSize(1160, 960); await tick();
      await run('setupSmoke.fail("complete")'); await click('Finish setup');
      assert.match(await run('document.querySelector("[role=alert]").textContent'), /Synthetic complete write failure/);
      assert.equal(await run('setupSmoke.state().setup.completedAt'), null);
      await click('Finish setup');
      assert.equal(await run('document.querySelector("[role=dialog]")'), null);
      assert.equal(await run('setupSmoke.state().setup.showOnStartup'), false);
      assert.ok(await run('setupSmoke.state().setup.completedAt > 0'));
      const reloaded = new Promise(resolve => window.webContents.once('did-finish-load', resolve));
      window.reload(); await reloaded; await tick();
      assert.equal(await value('input[placeholder="What should I call you?"]'), 'Alex', 'saved user survives reload');
      await click('Save and continue');
      assert.equal(await value('input[placeholder="Antimatter"]'), 'Nova', 'saved assistant survives reload');
      await click('Skip setup');
      assert.deepEqual(await models(), ['local:qwen3-32b', 'local:qwen3-coder-30b']);
      assert.deepEqual(await profiles(), ['profile-local']);
      await screenshot('models-local.png');
      await click('Distributed');
      assert.deepEqual(await models(), ['cluster:mimo-v2-flash']);
      assert.deepEqual(await profiles(), ['profile-distributed']);
      await screenshot('models-distributed.png');
      await click('Provider');
      assert.deepEqual(await models(), ['cloud:gpt-5.1']);
      assert.deepEqual(await profiles(), ['profile-provider']);
      await screenshot('models-provider.png');
      await click('Local');
      const card = '[data-model="local:qwen3-32b"]';
      await cardClick(card, 'Rename'); await input(`${card} input[aria-label="Rename Local thinker"]`, 'My local thinker');
      await run('setupSmoke.fail("metadata")'); await cardClick(card, 'Save name');
      assert.match(await run(`document.querySelector('${card} [role=alert]').textContent`), /Synthetic metadata write failure/);
      await cardClick(card, 'Save name');
      assert.equal(await run(`document.querySelector('${card} h3').textContent`), 'My local thinker');
      await cardClick(card, 'Edit settings');
      await select(`${card} [aria-label="Thinking level"]`, 'high');
      await cardClick(card, 'Save');
      assert.equal(await run('setupSmoke.profile("local", "qwen3-32b").thinkingLevel'), 'high');
      await screenshot('model-thinking.png');
      await cardClick(card, 'Close settings');
      await cardClick('[data-model="local:qwen3-coder-30b"]', 'Edit settings');
      assert.equal(await run(`document.querySelector('[data-model="local:qwen3-coder-30b"] [aria-label="Thinking level"]').disabled`), true);
      await cardClick('[data-model="local:qwen3-coder-30b"]', 'Close settings');
      await cardClick(card, 'Hide');
      assert.deepEqual(await models(), ['local:qwen3-coder-30b']);
      await run('document.querySelector("input[type=checkbox]").click()'); await tick();
      assert.deepEqual(await models(), ['local:qwen3-32b', 'local:qwen3-coder-30b']);
      await cardClick(card, 'Restore');
      await run('document.querySelector("input[type=checkbox]").click()'); await tick();
      assert.deepEqual(await models(), ['local:qwen3-32b', 'local:qwen3-coder-30b']);
      await cardClick('[data-profile="profile-local"]', 'Rename');
      await input('[aria-label="Rename Local assistant team"]', 'My local team');
      await cardClick('[data-profile="profile-local"]', 'Save');
      assert.match(await run(`document.querySelector('[data-profile="profile-local"]').textContent`), /My local team/);
      await run('setupSmoke.showDebug()'); await tick();
      assert.equal(await metric('Prefill time'), '—');
      assert.equal(await metric('Decode speed'), '—');
      assert.equal(await metric('Output tokens'), '—');
      await screenshot('debug-unreported.png');
      await select('[aria-label="Inference request"]', '1');
      assert.equal(await metric('Observed TTFT'), '450 ms');
      assert.equal(await metric('Prefill time'), '400 ms');
      assert.equal(await metric('Decode speed'), '50.0 tok/s');
      assert.equal(await metric('Reasoning tokens'), '100');
      await screenshot('debug-reported.png');
      window.setSize(680, 960); await tick();
      assert.ok(await run('document.documentElement.scrollWidth <= window.innerWidth'));
      await screenshot('models-debug-narrow.png');
      await run(`document.querySelector('[aria-label="Close inference debug overlay"]').click()`); await tick();
      await run('setupSmoke.openSetup()'); await tick();
      await screenshot('setup-narrow.png');
      assert.ok(await run('document.documentElement.scrollWidth <= window.innerWidth'));
      assert.deepEqual(await run('setupSmoke.actions'), []);
      assert.deepEqual(failures, []);
      console.log('Setup/models renderer smoke passed: user/personality save failures and persistence, Back, completion, strict category/model/profile filtering, rename/hide/restore, supported thinking and nonthinking control, actual/unreported metrics, responsive layout. No runtime, download, or network actions.');
      window.destroy(); app.exit(0);
    } catch (error) { console.error(error); await screenshot('setup-models-failure.png'); window.destroy(); app.exit(1); }
  }).catch((error) => { console.error(error); app.exit(1); });
}
