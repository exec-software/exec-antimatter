#!/usr/bin/env node
/** Synthetic local Bot chat IPC in the real settings, sidebar, and channel page. No real chats are messaged. */
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';

const filename = fileURLToPath(import.meta.url);
if (!process.versions.electron) {
  const { build } = await import('esbuild');
  const { default: electron } = await import('electron');
  const { default: postcss } = await import('postcss');
  const { default: tailwindcss } = await import('tailwindcss');
  const { default: tailwindConfig } = await import('../tailwind.config.js');
  const root = path.resolve(path.dirname(filename), '..');
  const output = await fs.mkdtemp(path.join(os.tmpdir(), 'antimatter-bot-chat-smoke-'));
  const assets = process.argv[2] ?? path.join(root, 'dist-electron/renderer/assets');
  for (const name of await fs.readdir(assets)) if (/\.(css|woff2?)$/.test(name)) await fs.copyFile(path.join(assets, name), path.join(output, name));
  // Compile current utilities so screenshots cover this new view before a full app rebuild.
  const css = await postcss([tailwindcss(tailwindConfig)]).process(await fs.readFile(path.join(root, 'renderer/src/index.css'), 'utf8'), { from: path.join(root, 'renderer/src/index.css') });
  await fs.writeFile(path.join(output, 'bot-chat.css'), css.css);
  await build({ entryPoints: [path.join(root, 'test/fixtures/bot-chat-renderer.tsx')], outfile: path.join(output, 'fixture.js'), bundle: true, platform: 'browser', format: 'esm' });
  const links = '<link rel="stylesheet" href="./bot-chat.css">';
  await fs.writeFile(path.join(output, 'index.html'), `<!doctype html><html><head><meta charset="UTF-8">${links}</head><body style="margin:0"><div id="root"></div><script type="module" src="./fixture.js"></script></body></html>`);
  console.log(`Bot chat smoke output: ${output}`);
  const child = spawn(electron, ['--no-sandbox', '--ozone-platform=headless', '--ozone-override-screen-size=1440,1024', filename, '--fixture', output], { stdio: 'inherit', env: { ...process.env, ELECTRON_RUN_AS_NODE: '' } });
  const deadline = setTimeout(() => { child.kill(); process.exitCode = 1; }, 30_000);
  child.on('error', (error) => { clearTimeout(deadline); console.error(error); process.exitCode = 1; });
  child.on('exit', (code) => { clearTimeout(deadline); process.exitCode = code ?? 1; });
} else {
  const { app, BrowserWindow, session } = await import('electron');
  const output = process.argv[process.argv.indexOf('--fixture') + 1];
  app.setPath('userData', path.join(output, 'user-data')); app.commandLine.appendSwitch('disable-gpu');
  app.whenReady().then(async () => {
    const isolated = session.fromPartition(`bot-chat-smoke-${process.pid}`);
    isolated.setPermissionRequestHandler((_contents, _permission, callback) => callback(false)); isolated.setPermissionCheckHandler(() => false);
    isolated.webRequest.onBeforeRequest((details, callback) => callback({ cancel: !details.url.startsWith('file:') && !details.url.startsWith('data:') }));
    const window = new BrowserWindow({ show: false, width: 1440, height: 1024, webPreferences: { session: isolated, nodeIntegration: false, contextIsolation: true, sandbox: true, offscreen: true } });
    const failures = []; window.webContents.on('console-message', (event) => { if (event.level === 'error') failures.push(event.message); });
    const run = (code) => window.webContents.executeJavaScript(code);
    const tick = () => run('new Promise(resolve => setTimeout(resolve, 150))');
    try {
      await window.loadFile(path.join(output, 'index.html')); await tick();
      const snap = () => run('botChatSmoke.snapshot()');
      let snapshot = await snap();
      assert.equal(snapshot.nav, false); assert.equal(snapshot.state.enabled, false);
      assert.match(snapshot.text, /selected model’s context/);
      await run('botChatSmoke.failConfigure(true); botChatSmoke.toggle("Allow public Bot chat across projects")'); await tick();
      snapshot = await snap(); assert.equal(snapshot.nav, false); assert.match(snapshot.alert, /Could not save the opt-in/);
      await run('botChatSmoke.failConfigure(false); botChatSmoke.toggle("Allow public Bot chat across projects")'); await tick();
      assert.equal((await snap()).nav, true);
      await run('botChatSmoke.click("Open Bot chat")'); await tick();
      snapshot = await snap(); assert.equal(snapshot.posts.length, 40); assert.equal(snapshot.images, 0);
      assert.match(snapshot.text, /Public result: <img src=x/); assert.match(snapshot.text, /Project: exec-lang-ny/);
      assert.equal(snapshot.mentionOptions.length, 3); assert.ok(snapshot.feed.remaining <= 2);
      await run('botChatSmoke.click("New public channel")'); await tick();
      await run('botChatSmoke.input("Public channel name", "coordination")'); await tick();
      await run('botChatSmoke.input("Public channel description", "Share only explicit public updates.")'); await tick();
      await run('botChatSmoke.click("Create channel")'); await tick();
      snapshot = await snap(); assert.match(snapshot.text, /#coordination/);
      await run('botChatSmoke.click("Edit channel")'); await tick();
      await run('botChatSmoke.input("Public channel name", "builds")'); await tick();
      await run('botChatSmoke.click("Save channel")'); await tick();
      assert.match((await snap()).text, /#builds/);
      await run('botChatSmoke.click("Pause posting")'); await tick();
      assert.equal((await snap()).postDisabled, true); assert.match((await snap()).text, /Posting paused/);
      await run('botChatSmoke.click("Resume posting")'); await tick();
      await run('botChatSmoke.click("Archive channel")'); await tick();
      assert.equal((await snap()).state.channels.find(channel => channel.name === 'builds').archived, true);
      await run('botChatSmoke.toggle("Show archived channels"); botChatSmoke.click("Open public channel general")'); await tick();
      await run('botChatSmoke.click("Open public channel builds")'); await tick();
      assert.equal((await snap()).postDisabled, true);
      await run('botChatSmoke.click("Restore channel")'); await tick();
      assert.equal((await snap()).state.channels.find(channel => channel.name === 'builds').archived, false);
      await run('botChatSmoke.click("Open public channel general")'); await tick();
      await run('botChatSmoke.scroll("top"); botChatSmoke.incoming()'); await tick();
      assert.equal((await snap()).feed.top, 0);
      await run('botChatSmoke.scroll("bottom"); botChatSmoke.incoming()'); await tick();
      assert.ok((await snap()).feed.remaining <= 2);
      await run('botChatSmoke.click("Older posts")'); await tick();
      snapshot = await snap(); assert.ok(snapshot.posts.length < 40); assert.equal(snapshot.feed.top, 0);
      const olderPosts = snapshot.posts;
      await run('botChatSmoke.incoming()'); await tick();
      assert.deepEqual((await snap()).posts, olderPosts);
      await run('botChatSmoke.click("Latest posts")'); await tick();
      await run('botChatSmoke.postAction("Public result:", "Reply")'); await tick();
      await run('botChatSmoke.mention("ui")'); await tick();
      await run('botChatSmoke.input("Public Bot chat post", "Human public note for the UI agent."); botChatSmoke.failPost(true)'); await tick();
      await run('botChatSmoke.click("Post publicly")'); await tick();
      snapshot = await snap(); assert.match(snapshot.alert, /could not be saved/); assert.equal(snapshot.draft, 'Human public note for the UI agent.');
      await run('botChatSmoke.failPost(false); botChatSmoke.click("Post publicly")'); await tick();
      snapshot = await snap(); const posts = snapshot.calls.filter(call => call.action === 'post');
      assert.equal(posts.length, 2); assert.equal(posts[0].args[1].clientMessageId, posts[1].args[1].clientMessageId);
      assert.equal(posts[1].args[1].replyTo, 'public-45'); assert.deepEqual(posts[1].args[1].mentionThreadIds, ['ui']);
      assert.equal(snapshot.draft, ''); assert.ok(snapshot.feed.remaining <= 2);
      assert.match(snapshot.posts.at(-1), /YouHuman/); assert.match(snapshot.posts.at(-1), /@Antimatter UI/);
      await fs.writeFile(path.join(output, 'bot-chat-dark.png'), (await window.webContents.capturePage()).toPNG());
      await run('botChatSmoke.appearance({theme:"light",secondaryAccent:"#176f83"})'); await tick();
      assert.equal((await snap()).requestedAccent, '#176f83');
      assert.notEqual((await snap()).accent, snapshot.accent); // The palette adjusts the chosen shade for readable contrast.
      await fs.writeFile(path.join(output, 'bot-chat-light.png'), (await window.webContents.capturePage()).toPNG());
      await run('botChatSmoke.input("Public Bot chat post", "Preserve this channel draft")'); await tick();
      await run('botChatSmoke.click("Open public channel builds")'); await tick();
      assert.equal((await snap()).draft, '');
      await run('botChatSmoke.click("Open public channel general")'); await tick();
      assert.equal((await snap()).draft, 'Preserve this channel draft');
      await run('botChatSmoke.click("Open public channel slow")'); await tick();
      await run('botChatSmoke.click("Open public channel general")'); await tick();
      await run('botChatSmoke.releaseRead()'); await tick();
      assert.ok(!(await snap()).text.includes('STALE CHANNEL DESCRIPTION'));
      await run('botChatSmoke.click("Open source chat Ny compiler")'); await tick();
      assert.deepEqual((await snap()).opened, ['ny']);
      await run('botChatSmoke.settings()'); await tick();
      await run('botChatSmoke.toggle("Allow public Bot chat across projects")'); await tick();
      snapshot = await snap(); assert.equal(snapshot.nav, false); assert.equal(snapshot.state.enabled, false);
      await run('botChatSmoke.click("Review saved history")'); await tick();
      snapshot = await snap(); assert.match(snapshot.text, /Bot chat is off/); assert.equal(snapshot.postDisabled, true);
      assert.equal(snapshot.draft, 'Preserve this channel draft');
      assert.match(snapshot.text, /Human public note for the UI agent/);
      await run('botChatSmoke.postAction("Human public note for the UI agent", "Redact")'); await tick();
      assert.equal((await snap()).focused, 'Cancel');
      await run('botChatSmoke.click("Cancel")'); await tick();
      assert.equal((await snap()).calls.filter(call => call.action === 'moderate').length, 0);
      await run('botChatSmoke.postAction("Human public note for the UI agent", "Redact")'); await tick();
      await run('botChatSmoke.click("Redact public post")'); await tick();
      snapshot = await snap(); assert.match(snapshot.text, /Post redacted/); assert.ok(!snapshot.text.includes('Human public note for the UI agent'));
      assert.equal(snapshot.calls.filter(call => call.action === 'moderate').length, 1);
      assert.deepEqual(failures, []);
      console.log('Bot chat smoke passed: opt-in persistence/error and sidebar visibility, channel create/edit/pause/archive/restore, attributed plain-text posts, public participant mentions/replies, explicit human posting with stable retry ID, drafts, bounded history/live scrolling, stale reads, source navigation, disabled history review and confirmed redaction.');
      window.destroy(); app.exit(0);
    } catch (error) {
      console.error(error, failures);
      await fs.writeFile(path.join(output, 'failure.png'), (await window.webContents.capturePage()).toPNG());
      window.destroy(); app.exit(1);
    }
  }).catch((error) => { console.error(error); app.exit(1); });
}
