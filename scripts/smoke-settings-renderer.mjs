#!/usr/bin/env node
/** Native renderer-only settings smoke. All IPC is mocked; network and permission access are denied. */
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';

const filename = fileURLToPath(import.meta.url);
if (!process.versions.electron) {
  const { build } = await import('esbuild');
  const { default: electron } = await import('electron');
  const root = path.resolve(path.dirname(filename), '..');
  const outputRoot = process.env.ANTIMATTER_SMOKE_ROOT ?? '/var/tmp';
  await fs.mkdir(outputRoot, { recursive: true });
  const output = await fs.mkdtemp(path.join(outputRoot, 'antimatter-settings-smoke-'));
  await build({ entryPoints: [path.join(root, 'test/fixtures/settings-renderer.tsx')], outfile: path.join(output, 'fixture.js'), bundle: true, platform: 'browser', format: 'esm', jsx: 'automatic', define: { 'process.env.NODE_ENV': '"production"' }, loader: { '.js': 'jsx' } });
  const { default: postcss } = await import('postcss');
  const { default: tailwindcss } = await import('tailwindcss');
  const { default: tailwindConfig } = await import('../tailwind.config.js');
  const css = await postcss([tailwindcss(tailwindConfig)]).process(await fs.readFile(path.join(root, 'renderer/src/index.css'), 'utf8'), { from: path.join(root, 'renderer/src/index.css') });
  await fs.writeFile(path.join(output, 'fixture.css'), css.css);
  await fs.cp(path.join(root, 'renderer/src/assets/fonts'), path.join(output, 'assets/fonts'), { recursive: true });
  await fs.writeFile(path.join(output, 'index.html'), '<!doctype html><html><head><meta charset="UTF-8"><meta http-equiv="Content-Security-Policy" content="default-src \'none\'; script-src \'self\'; style-src \'self\' \'unsafe-inline\'; font-src \'self\'; img-src \'self\' data:; connect-src \'none\'; media-src \'none\'"><link rel="stylesheet" href="fixture.css"></head><body><div id="root"></div><script type="module" src="fixture.js"></script></body></html>');
  console.log(`Settings smoke output: ${output}`);
  const child = spawn(electron, ['--no-sandbox', '--ozone-platform=headless', '--ozone-override-screen-size=1440,1200', filename, '--fixture', output], { stdio: 'inherit', env: { ...process.env, ELECTRON_RUN_AS_NODE: '' } });
  const deadline = setTimeout(() => { console.error('Settings fixture timed out; stopping only the isolated fixture.'); child.kill(); process.exitCode = 1; }, 30_000);
  child.on('error', (error) => { console.error(error); process.exitCode = 1; });
  child.on('exit', (code) => { clearTimeout(deadline); process.exitCode = code ?? 1; });
} else {
  const { app, BrowserWindow, session } = await import('electron');
  const output = process.argv[process.argv.indexOf('--fixture') + 1];
  app.setPath('userData', path.join(output, 'user-data'));
  app.commandLine.appendSwitch('disable-gpu');
  app.whenReady().then(async () => {
    const isolated = session.fromPartition(`settings-smoke-${process.pid}`);
    isolated.setPermissionRequestHandler((_contents, _permission, callback) => callback(false));
    isolated.setPermissionCheckHandler(() => false);
    isolated.webRequest.onBeforeRequest((details, callback) => callback({ cancel: !details.url.startsWith('file:') && !details.url.startsWith('data:') }));
    const window = new BrowserWindow({ show: false, width: 1160, height: 960, enableLargerThanScreen: true, webPreferences: { session: isolated, nodeIntegration: false, contextIsolation: true, sandbox: true, offscreen: true } });
    const failures = [];
    window.webContents.on('console-message', (event) => { if (event.level === 'error') { failures.push(event.message); console.error('Fixture renderer:', event.message); } });
    const run = (code) => window.webContents.executeJavaScript(code);
    const tick = () => run('new Promise(resolve => setTimeout(resolve, 80))');
    const click = async (label) => { await run(`(() => { const button = [...document.querySelectorAll('button')].find(item => item.checkVisibility() && item.textContent.trim() === ${JSON.stringify(label)}); if (!button || button.disabled) throw Error('Unavailable button: ' + ${JSON.stringify(label)}); button.click(); })()`); await tick(); };
    const input = async (selector, value) => { await run(`(() => { const element = document.querySelector(${JSON.stringify(selector)}); if (!element || !element.checkVisibility()) throw Error('Unavailable input'); Object.getOwnPropertyDescriptor(element instanceof HTMLTextAreaElement ? HTMLTextAreaElement.prototype : HTMLInputElement.prototype, 'value').set.call(element, ${JSON.stringify(value)}); element.dispatchEvent(new Event('input', { bubbles: true })); })()`); await tick(); };
    const navigate = async (target) => { await run(`settingsSmoke.navigate(${JSON.stringify(target)})`); await tick(); };
    const value = (selector) => run(`document.querySelector(${JSON.stringify(selector)}).value`);
    const screenshot = async (name) => fs.writeFile(path.join(output, name), (await window.webContents.capturePage()).toPNG());
    try {
      await window.loadFile(path.join(output, 'index.html')); await tick();
      assert.equal(await run('settingsSmoke.reads.engineInfo ?? 0'), 0);
      assert.equal(await run('settingsSmoke.reads.engineStatus ?? 0'), 0);
      assert.equal(await run('settingsSmoke.reads.downloads ?? 0'), 0);
      assert.equal(await run('settingsSmoke.reads.voice ?? 0'), 0);
      await screenshot('settings-general.png');
      await navigate({ section: 'appearance' });
      assert.equal(await run('document.documentElement.dataset.theme'), 'dark');
      assert.equal(await run('document.querySelector("[aria-label=\\"Dark theme\\"]").checked'), true);
      await run('document.querySelector("[aria-label=\\"Light theme\\"]").click()'); await tick();
      assert.equal(await run('document.documentElement.style.colorScheme'), 'light');
      await click('Violet');
      assert.equal(await value('[aria-label="Accent hex value"]'), '#665492', 'the light theme has its own presets');
      await screenshot('settings-appearance-light.png');
      const beforeFailure = await run('getComputedStyle(document.documentElement).getPropertyValue("--color-accent")');
      await input('[aria-label="Accent hex value"]', '#oops');
      assert.equal(await run('document.querySelector("[aria-label=\\"Accent hex value\\"]").getAttribute("aria-invalid")'), 'true');
      assert.equal(await run('[...document.querySelectorAll("button")].find(b => b.textContent === "Apply color").disabled'), true);
      await input('[aria-label="Accent hex value"]', '#629cf5');
      await run('settingsSmoke.failAppearance()'); await click('Apply color');
      assert.equal(await run('getComputedStyle(document.documentElement).getPropertyValue("--color-accent")'), beforeFailure);
      assert.match(await run('document.querySelector("[role=alert]").textContent'), /Could not save appearance/);
      await click('Apply color');
      assert.notEqual(await run('getComputedStyle(document.documentElement).getPropertyValue("--color-accent")'), beforeFailure);
      const reloaded = new Promise(resolve => window.webContents.once('did-finish-load', resolve));
      window.reload(); await reloaded; await tick();
      assert.equal(await run('document.documentElement.dataset.theme'), 'light');
      await navigate({ section: 'appearance' });
      assert.equal(await value('[aria-label="Accent hex value"]'), '#629cf5');
      await input('[aria-label="Accent hex value"]', '#aabbcc');
      await click('Models'); await click('Appearance');
      assert.equal(await value('[aria-label="Accent hex value"]'), '#aabbcc', 'unsaved color draft survives category changes');
      await click('Reset to dark & teal');
      assert.equal(await run('document.documentElement.dataset.theme'), 'dark');
      assert.equal(await value('[aria-label="Accent hex value"]'), '#33b7a6');
      await input('[aria-label="Accent hex value"]', '#aabbcc');
      await click('Reset to dark & teal');
      assert.equal(await value('[aria-label="Accent hex value"]'), '#33b7a6', 'reset also clears an unsaved draft when stored settings are already defaults');
      await screenshot('settings-appearance-dark.png');
      await click('General');
      // Notifications: both channels on by default, the four built-ins offered with sound off,
      // and a toggle written through rather than only shown.
      assert.equal(await run('document.querySelectorAll(\'input[name="notification-sound"]\').length'), 4);
      assert.equal(await run('document.querySelector(\'input[name="notification-sound"][value="chime"]\').checked'), true);
      assert.equal(await run('document.querySelector(\'[aria-label="Notification volume"]\').value'), '0.6');
      await run('document.querySelector(\'[aria-label="Notification sound"]\').click()'); await tick();
      assert.equal(await run('settingsSmoke.notificationWrites.at(-1).sound'), false);
      assert.equal(await run('document.querySelectorAll(\'input[name="notification-sound"]\').length'), 4, 'sounds stay auditionable with sound off');
      await run('document.querySelector(\'[aria-label="Desktop notification"]\').click()'); await tick();
      assert.equal(await run('settingsSmoke.notificationWrites.at(-1).desktop'), false);
      assert.equal(await run('document.querySelector(\'[aria-label="Desktop notification"]\').checked'), false);
      await input('input[placeholder="What to call you"]', 'Unsaved profile');
      await click('Models');
      assert.equal(await run('settingsSmoke.reads.engineInfo ?? 0'), 0);
      assert.equal(await run('settingsSmoke.reads.downloads ?? 0'), 0);
      assert.equal(await run(`document.querySelector('input[placeholder="What to call you"]').checkVisibility()`), false);
      await screenshot('settings-models.png');
      await click('Add source');
      await input('#settings-add-source input', 'Unsaved source');
      await click('Voice');
      await input('[aria-label="Audio input model"]', 'unsaved-audio-model');
      await click('General');
      assert.equal(await value('input[placeholder="What to call you"]'), 'Unsaved profile');
      await click('Models');
      assert.equal(await run('document.querySelector("#settings-add-source input").value'), 'Unsaved source');
      await click('Close add source'); await click('Add source');
      assert.equal(await run('document.querySelector("#settings-add-source input").value'), 'Unsaved source');
      await click('Close add source');
      await click('Voice');
      assert.equal(await value('[aria-label="Audio input model"]'), 'unsaved-audio-model');
      assert.equal(await run(`document.querySelectorAll('nav[aria-label="Settings categories"] [aria-current="page"]').length`), 1);
      await screenshot('settings-voice.png');
      await click('Remote devices');
      await click('Add device');
      assert.equal(await run('document.querySelector("img")?.checkVisibility()'), true);
      await screenshot('settings-devices.png');
      await click('General');
      assert.ok(await run('settingsSmoke.cancellations.includes(settingsSmoke.offerId)'));
      assert.equal(await run('document.querySelector("img")'), null);
      await navigate({ section: 'models', detail: 'engine' });
      assert.equal(await run('document.querySelector("#settings-content-engine").hidden'), false);
      assert.ok(await run('settingsSmoke.reads.engineInfo > 0 && settingsSmoke.reads.engineStatus > 0'));
      await input('#settings-content-engine input:nth-of-type(1)', '/fixture/unsaved-config.toml');
      await input('#settings-content-engine .sm\\:grid-cols-2 label:first-child input', '127.0.0.2');
      await input('#settings-content-engine .sm\\:grid-cols-2 label:last-child input', '7777');
      await click('Retry engine information');
      assert.equal(await run('settingsSmoke.reads.engineInfo'), 2);
      assert.equal(await value('#settings-content-engine input:nth-of-type(1)'), '/fixture/unsaved-config.toml');
      assert.equal(await value('#settings-content-engine .sm\\:grid-cols-2 label:first-child input'), '127.0.0.2');
      assert.equal(await value('#settings-content-engine .sm\\:grid-cols-2 label:last-child input'), '7777');
      assert.equal(await run('document.querySelector("#settings-content-engine [role=alert]")'), null);
      await navigate({ section: 'models', detail: 'downloads' });
      assert.equal(await run('document.querySelector("#settings-content-downloads").hidden'), false);
      assert.ok(await run('settingsSmoke.reads.downloads > 0'));
      await input('[aria-label="Hugging Face token"]', 'unsaved-fixture-token');
      await click('General'); await click('Models');
      assert.equal(await value('[aria-label="Hugging Face token"]'), 'unsaved-fixture-token');
      await input('[aria-label="Hugging Face token"]', '');
      await screenshot('settings-model-details.png');
      window.setSize(680, 960); await tick();
      await navigate({ section: 'general' });
      assert.ok(await run('document.documentElement.scrollWidth <= window.innerWidth'));
      await screenshot('settings-narrow.png');
      await click('Updates & about');
      await screenshot('settings-updates.png');
      assert.deepEqual(await run('settingsSmoke.actions'), []);
      assert.deepEqual(failures, []);
      console.log('Settings renderer smoke passed: saved dark/light/presets/custom accent, invalid input/write failure/reload/reset, category draft retention, lazy reads, QR cancellation, engine retry, deep links, responsive layout. No lifecycle calls, device access, or network.');
      window.destroy(); app.exit(0);
    } catch (error) { console.error(error); await screenshot('settings-failure.png'); window.destroy(); app.exit(1); }
  }).catch((error) => { console.error(error); app.exit(1); });
}
