#!/usr/bin/env node
/** Synthetic engine profile IPC in the real model card. No services or conversations are changed. */
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';

const filename = fileURLToPath(import.meta.url);
if (!process.versions.electron) {
  const { build } = await import('esbuild');
  const { default: electron } = await import('electron');
  const { default: postcss } = await import('postcss');
  const { default: tailwindcss } = await import('tailwindcss');
  const { default: tailwindConfig } = await import('../tailwind.config.js');
  const root = path.resolve(path.dirname(filename), '..');
  const output = await fs.mkdtemp(path.join(os.tmpdir(), 'antimatter-model-runtime-profiles-smoke-'));
  const assets = process.argv[2] ?? path.join(root, 'dist-electron/renderer/assets');
  for (const name of await fs.readdir(assets)) if (/\.(css|woff2?)$/.test(name)) await fs.copyFile(path.join(assets, name), path.join(output, name));
  // Compile current utilities so screenshots cover this new view before a full app rebuild.
  const css = await postcss([tailwindcss(tailwindConfig)]).process(await fs.readFile(path.join(root, 'renderer/src/index.css'), 'utf8'), { from: path.join(root, 'renderer/src/index.css') });
  await fs.writeFile(path.join(output, 'model-runtime-profiles.css'), css.css);
  await build({ entryPoints: [path.join(root, 'test/fixtures/model-runtime-profiles-renderer.tsx')], outfile: path.join(output, 'fixture.js'), bundle: true, platform: 'browser', format: 'esm' });
  const links = '<link rel="stylesheet" href="./model-runtime-profiles.css">';
  await fs.writeFile(path.join(output, 'index.html'), `<!doctype html><html><head><meta charset="UTF-8">${links}</head><body style="margin:0"><div id="root"></div><script type="module" src="./fixture.js"></script></body></html>`);
  console.log(`Model runtime profiles smoke output: ${output}`);
  const child = spawn(electron, ['--no-sandbox', '--ozone-platform=headless', '--ozone-override-screen-size=1280,960', filename, '--fixture', output], { stdio: 'inherit', env: { ...process.env, ELECTRON_RUN_AS_NODE: '' } });
  const deadline = setTimeout(() => { child.kill(); process.exitCode = 1; }, 30_000);
  child.on('error', (error) => { clearTimeout(deadline); console.error(error); process.exitCode = 1; });
  child.on('exit', (code) => { clearTimeout(deadline); process.exitCode = code ?? 1; });
} else {
  const { app, BrowserWindow, session } = await import('electron');
  const output = process.argv[process.argv.indexOf('--fixture') + 1];
  app.setPath('userData', path.join(output, 'user-data')); app.commandLine.appendSwitch('disable-gpu');
  app.whenReady().then(async () => {
    const isolated = session.fromPartition(`model-runtime-profiles-smoke-${process.pid}`);
    isolated.setPermissionRequestHandler((_contents, _permission, callback) => callback(false)); isolated.setPermissionCheckHandler(() => false);
    isolated.webRequest.onBeforeRequest((details, callback) => callback({ cancel: !details.url.startsWith('file:') && !details.url.startsWith('data:') }));
    const window = new BrowserWindow({ show: false, width: 920, height: 980, webPreferences: { session: isolated, nodeIntegration: false, contextIsolation: true, sandbox: true, offscreen: true } });
    const failures = []; window.webContents.on('console-message', (event) => { if (event.level === 'error') failures.push(event.message); });
    const run = (code) => window.webContents.executeJavaScript(code);
    const tick = () => run('new Promise(resolve => setTimeout(resolve, 150))');
    try {
      await window.loadFile(path.join(output, 'index.html')); await tick();
      const snap = () => run('runtimeProfilesSmoke.snapshot()');
      const disabled = (snapshot, label) => snapshot.buttons.find(button => button.label === label)?.disabled;
      let snapshot = await snap();
      assert.equal(snapshot.calls.length, 0);
      await run('runtimeProfilesSmoke.click("Engine profiles")'); await tick();
      snapshot = await snap();
      assert.match(snapshot.text, /131,072 tokens per slot · 1 parallel slot/);
      await run('runtimeProfilesSmoke.click("Create engine profiles")'); await tick();
      snapshot = await snap();
      assert.equal(snapshot.state.activeProfileId, 'baseline');
      assert.deepEqual(snapshot.state.actual, { contextTokens: 131072, parallel: 1 });
      assert.ok(snapshot.inputs.every(input => input.disabled));
      assert.equal(disabled(snapshot, 'Delete profile'), undefined);
      assert.equal(snapshot.calls.filter(call => call.action === 'apply').length, 0);
      await run('runtimeProfilesSmoke.select("Orchestration")'); await tick();
      snapshot = await snap();
      assert.deepEqual(snapshot.inputs.map(input => input.value), ['Orchestration', '32768', '2']);
      assert.match(snapshot.text, /65,536 total context tokens/);
      await run('runtimeProfilesSmoke.busy(true)'); await tick();
      assert.equal(disabled(await snap(), 'Apply profile'), true);
      await run('runtimeProfilesSmoke.busy(false)'); await tick();
      await run('runtimeProfilesSmoke.click("Apply profile")'); await tick();
      snapshot = await snap();
      assert.match(snapshot.text, /Reloading the model and verifying/);
      assert.equal(snapshot.state.activeProfileId, 'baseline');
      await run('runtimeProfilesSmoke.releaseApply()'); await tick();
      snapshot = await snap();
      assert.equal(snapshot.state.activeProfileId, 'orchestration');
      assert.ok(snapshot.inputs.every(input => input.disabled));
      assert.equal(disabled(snapshot, 'Delete profile'), undefined);
      await run('runtimeProfilesSmoke.click("Make a copy")'); await tick();
      await run('runtimeProfilesSmoke.edit("Engine profile name", "My team"); runtimeProfilesSmoke.edit("Engine context per slot", "24576")'); await tick();
      await run('runtimeProfilesSmoke.edit("Engine parallel slots", "3")'); await tick();
      snapshot = await snap();
      assert.equal(disabled(snapshot, 'Apply profile'), true);
      assert.match(snapshot.text, /73,728 total context tokens/);
      await run('runtimeProfilesSmoke.click("Save profile")'); await tick();
      snapshot = await snap();
      assert.equal(snapshot.state.activeProfileId, 'orchestration');
      assert.deepEqual(snapshot.calls.find(call => call.action === 'update').args, ['local', 'deepseek', 'copy', { name: 'My team', contextTokens: 24576, parallel: 3 }]);
      await run('runtimeProfilesSmoke.failApply(true); runtimeProfilesSmoke.click("Apply profile")'); await tick();
      await run('runtimeProfilesSmoke.releaseApply()'); await tick();
      snapshot = await snap();
      assert.match(snapshot.alert, /failed verification/); assert.equal(snapshot.state.activeProfileId, 'orchestration');
      await run('runtimeProfilesSmoke.failApply(false); runtimeProfilesSmoke.select("Straight shot")'); await tick();
      await run('runtimeProfilesSmoke.click("Apply profile")'); await tick();
      await run('runtimeProfilesSmoke.releaseApply()'); await tick();
      snapshot = await snap();
      assert.deepEqual(snapshot.state.actual, { contextTokens: 131072, parallel: 1 });
      assert.equal(snapshot.state.activeProfileId, 'baseline');
      await run('runtimeProfilesSmoke.select("My team")'); await tick();
      await fs.writeFile(path.join(output, 'model-runtime-profiles-dark.png'), (await window.webContents.capturePage()).toPNG());
      await run('runtimeProfilesSmoke.appearance({theme:"light",secondaryAccent:"#176f83"})'); await tick();
      await fs.writeFile(path.join(output, 'model-runtime-profiles-light.png'), (await window.webContents.capturePage()).toPNG());
      await run('runtimeProfilesSmoke.edit("Engine parallel slots", "0")'); await tick();
      assert.equal(disabled(await snap(), 'Save profile'), true);
      await run('runtimeProfilesSmoke.click("Discard edits")'); await tick();
      snapshot = await snap();
      assert.equal(snapshot.inputs.find(input => input.label === 'Engine profile name').maxLength, 100);
      await run('runtimeProfilesSmoke.edit("Engine profile name", "x".repeat(101))'); await tick();
      assert.equal(disabled(await snap(), 'Save profile'), true);
      await run('runtimeProfilesSmoke.click("Discard edits")'); await tick();
      await run('runtimeProfilesSmoke.click("Delete profile")'); await tick();
      snapshot = await snap();
      assert.match(snapshot.text, /Delete this engine profile/); assert.equal(snapshot.focused, 'Cancel');
      assert.equal(snapshot.calls.filter(call => call.action === 'remove').length, 0);
      await run('runtimeProfilesSmoke.click("Cancel")'); await tick();
      assert.equal((await snap()).calls.filter(call => call.action === 'remove').length, 0);
      await run('runtimeProfilesSmoke.click("Delete profile")'); await tick();
      await run('runtimeProfilesSmoke.click("Delete saved profile")'); await tick();
      snapshot = await snap();
      assert.deepEqual(snapshot.calls.find(call => call.action === 'remove').args, ['local', 'deepseek', 'copy']);
      assert.equal(snapshot.state.profiles.some(profile => profile.id === 'copy'), false);
      assert.equal(snapshot.state.activeProfileId, 'baseline');
      assert.deepEqual(snapshot.state.actual, { contextTokens: 131072, parallel: 1 });
      assert.equal(snapshot.inputs[0].value, 'Straight shot');
      assert.equal(disabled(snapshot, 'Delete profile'), undefined);
      const beforeRecovery = snapshot.calls.filter(call => call.action === 'apply').length;
      await run('runtimeProfilesSmoke.select("Orchestration")'); await tick();
      await run('runtimeProfilesSmoke.failEngine()'); await tick();
      snapshot = await snap();
      assert.match(snapshot.text, /Engine recovery/); assert.match(snapshot.text, /local engine stopped/);
      assert.equal(snapshot.inputs[0].value, 'Orchestration');
      assert.ok(snapshot.inputs.every(input => input.disabled));
      assert.equal(disabled(snapshot, 'Apply profile'), undefined);
      assert.equal(disabled(snapshot, 'Make a copy'), undefined);
      assert.equal(disabled(snapshot, 'Save profile'), undefined);
      assert.equal(disabled(snapshot, 'Delete profile'), undefined);
      assert.equal(snapshot.calls.filter(call => call.action === 'apply').length, beforeRecovery);
      await fs.writeFile(path.join(output, 'model-runtime-profiles-recovery.png'), (await window.webContents.capturePage()).toPNG());
      await run('runtimeProfilesSmoke.busy(true)'); await tick();
      assert.equal(disabled(await snap(), 'Restore Straight shot'), true);
      await run('runtimeProfilesSmoke.busy(false); runtimeProfilesSmoke.failApply(true)'); await tick();
      await run('runtimeProfilesSmoke.click("Restore Straight shot")'); await tick();
      snapshot = await snap();
      assert.equal(snapshot.state.activeProfileId, null);
      assert.deepEqual(snapshot.calls.filter(call => call.action === 'apply').at(-1).args, ['local', 'deepseek', 'baseline']);
      await run('runtimeProfilesSmoke.releaseApply()'); await tick();
      snapshot = await snap();
      assert.match(snapshot.alert, /recovery failed/);
      assert.equal(snapshot.state.activeProfileId, null); assert.equal(snapshot.state.actual, null);
      assert.equal(snapshot.calls.filter(call => call.action === 'apply').length, beforeRecovery + 1);
      await run('runtimeProfilesSmoke.failApply(false); runtimeProfilesSmoke.click("Restore Straight shot")'); await tick();
      await run('runtimeProfilesSmoke.releaseApply()'); await tick();
      snapshot = await snap();
      assert.equal(snapshot.state.recoveryOnly, false);
      assert.equal(snapshot.state.activeProfileId, 'baseline');
      assert.equal(snapshot.inputs[0].value, 'Straight shot');
      assert.deepEqual(snapshot.state.actual, { contextTokens: 131072, parallel: 1 });
      await run('runtimeProfilesSmoke.source("slow")'); await tick();
      await run('runtimeProfilesSmoke.source("provider")'); await tick();
      await run('runtimeProfilesSmoke.releaseRead()'); await tick();
      snapshot = await snap();
      assert.match(snapshot.text, /Provider manages its own engine capacity/);
      assert.equal(snapshot.inputs.length, 0); assert.ok(!snapshot.text.includes('STALE SOURCE'));
      assert.deepEqual(failures, []);
      console.log('Model runtime profiles smoke passed: ModelCard integration, protected profiles, capture/save/apply, copied edits, pool arithmetic, busy/reload/verification states, failed apply and explicit stopped-engine recovery, baseline restoration, confirmed inactive deletion, validation and stale-source protection.');
      window.destroy(); app.exit(0);
    } catch (error) {
      console.error(error, failures);
      await fs.writeFile(path.join(output, 'failure.png'), (await window.webContents.capturePage()).toPNG());
      window.destroy(); app.exit(1);
    }
  }).catch((error) => { console.error(error); app.exit(1); });
}
