#!/usr/bin/env node
/** Isolated memory library and feature-management interaction smoke. */
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';

const filename = fileURLToPath(import.meta.url);
if (!process.versions.electron) {
  const { build } = await import('esbuild');
  const { default: electron } = await import('electron');
  const root = path.resolve(path.dirname(filename), '..');
  const output = await fs.mkdtemp(path.join(os.tmpdir(), 'antimatter-settings-workflow-'));
  const assets = process.argv[2] ?? path.join(root, 'dist-electron/renderer/assets');
  for (const name of await fs.readdir(assets)) if (/\.(css|woff2?)$/.test(name)) await fs.copyFile(path.join(assets, name), path.join(output, name));
  await build({ entryPoints: [path.join(root, 'test/fixtures/settings-workflow-renderer.tsx')], outfile: path.join(output, 'fixture.js'), bundle: true, platform: 'browser', format: 'esm' });
  const links = (await fs.readdir(output)).filter((name) => name.endsWith('.css')).map((name) => `<link rel="stylesheet" href="./${name}">`).join('');
  await fs.writeFile(path.join(output, 'index.html'), `<!doctype html><html><head><meta charset="UTF-8">${links}</head><body style="margin:0"><div id="root"></div><script type="module" src="./fixture.js"></script></body></html>`);
  console.log(`Settings workflow smoke output: ${output}`);
  const child = spawn(electron, ['--no-sandbox', '--ozone-platform=headless', '--ozone-override-screen-size=1280,960', filename, '--fixture', output], { stdio: 'inherit', env: { ...process.env, ELECTRON_RUN_AS_NODE: '' } });
  const deadline = setTimeout(() => { child.kill(); process.exitCode = 1; }, 60_000);
  child.on('error', (error) => { clearTimeout(deadline); console.error(error); process.exitCode = 1; });
  child.on('exit', (code) => { clearTimeout(deadline); process.exitCode = code ?? 1; });
} else {
  const { app, BrowserWindow, session } = await import('electron');
  const output = process.argv[process.argv.indexOf('--fixture') + 1];
  app.setPath('userData', path.join(output, 'user-data')); app.commandLine.appendSwitch('disable-gpu');
  app.whenReady().then(async () => {
    const isolated = session.fromPartition(`settings-workflow-smoke-${process.pid}`);
    isolated.setPermissionRequestHandler((_contents, _permission, callback) => callback(false)); isolated.setPermissionCheckHandler(() => false);
    isolated.webRequest.onBeforeRequest((details, callback) => callback({ cancel: !details.url.startsWith('file:') && !details.url.startsWith('data:') }));
    const window = new BrowserWindow({ show: false, width: 1280, height: 900, webPreferences: { session: isolated, nodeIntegration: false, contextIsolation: true, sandbox: true, offscreen: true } });
    const failures = []; window.webContents.on('console-message', (event) => { if (event.level === 'error') failures.push(event.message); });
    const run = (code) => window.webContents.executeJavaScript(code);
    const tick = () => run('new Promise(resolve => setTimeout(resolve, 150))');
    try {
      await window.loadFile(path.join(output, 'index.html')); await tick();
      const screenshot = async name => fs.writeFile(path.join(output, name), (await window.webContents.capturePage()).toPNG());
      const click = async label => { await run(`settingsSmoke.click(${JSON.stringify(label)})`); await tick(); };
      const change = async (label, value) => { await run(`settingsSmoke.change(${JSON.stringify(label)}, ${JSON.stringify(value)})`); await tick(); };
      const toggle = async label => { await run(`settingsSmoke.toggle(${JSON.stringify(label)})`); await tick(); };
      const snapshot = () => run('settingsSmoke.snapshot()');
      const call = async expression => { await run(`settingsSmoke.${expression}`); await tick(); };
      await click('Rust reference');
      assert.equal(await run("document.querySelector('article script') === null && !window.untrusted"), true);
      assert.equal(await run("document.querySelector('article [aria-label=\"Read-only\"]') !== null"), true);
      assert.equal(await run("[...document.querySelectorAll('article button')].some(item => item.textContent === 'Edit')"), false);
      await toggle('Use library in chats'); assert.equal((await snapshot()).memory.enabled, true);
      await toggle('Enable Rust reference'); assert.equal((await snapshot()).memory.entries[0].enabled, false);
      await click('Add entry'); await change('Entry title', 'My draft'); await call('storageFailure(true)'); await change('Entry content', 'Local content <img src=x onerror=alert(1)>');
      assert.match((await snapshot()).text, /Could not save the draft/);
      assert.ok((await run('settingsSmoke.draftBlockers()')).length);
      await call('storageFailure(false)'); await click('Retry draft storage');
      assert.deepEqual(await run('settingsSmoke.draftBlockers()'), []);
      await change('Entry language', 'cpp'); await change('Entry scope', 'project');
      await call("workspace('/fixture/project-b')"); assert.equal((await snapshot()).form['Entry title'], undefined);
      await call("workspace('/fixture/project-a')"); assert.equal((await snapshot()).form['Entry title'].value, 'My draft');
      await call("page('other')"); await call("page('memory')");
      assert.equal((await snapshot()).form['Entry content'].value, 'Local content <img src=x onerror=alert(1)>');
      await window.reload(); await tick();
      let current = await snapshot(); assert.equal(current.form['Entry title'].value, 'My draft');
      // Restart reset this fixture's in-memory host, so explicitly reconcile the saved revision.
      if (current.saveDisabled) await click('Keep my draft');
      await call('storageFailure(false, true)'); await click('Save'); current = await snapshot();
      assert.equal(current.memory.entries[1].title, 'My draft'); assert.equal(current.memory.entries[1].language, 'cpp');
      assert.equal(current.memory.entries[1].scope, 'project'); assert.equal(current.form['Entry title'], undefined);
      assert.match(current.text, /Could not remove the saved draft/);
      assert.ok((await run('settingsSmoke.draftBlockers()')).length);
      await call('storageFailure(false)'); await click('Retry draft storage'); current = await snapshot();
      assert.equal(Object.keys(current.storage).some(key => key.startsWith('antimatter.form-draft.')), false);
      await click('Edit'); await change('Entry content', 'My edited content'); await call('memoryConflict()');
      current = await snapshot(); assert.equal(current.saveDisabled, true); assert.equal(current.form['Entry content'].value, 'My edited content');
      assert.match(current.text, /library changed while you were editing/);
      await click('Keep my draft'); await click('Save'); assert.equal((await snapshot()).memory.entries[1].content, 'My edited content');
      await click('Edit'); await change('Entry content', 'Discard this text'); await call('memoryConflict()'); await click('Use saved version');
      assert.equal((await snapshot()).form['Entry content'].value, 'External saved content');
      await click('Discard'); await click('Cancel'); assert.equal((await snapshot()).form['Entry title'].value, 'My draft');
      await click('Discard'); await click('Discard draft'); assert.equal((await snapshot()).form['Entry title'], undefined);
      await screenshot('memory-library-desktop.png');
      await click('Delete My draft'); await click('Keep'); assert.equal((await snapshot()).memory.entries.length, 2);
      await click('Delete My draft'); await click('Delete'); assert.equal((await snapshot()).memory.entries.length, 1);
      await call(`savedDraft('feature-management', '{ unreadable saved bytes')`); await call("page('features')");
      assert.match((await snapshot()).text, /saved draft could not be read/);
      assert.equal((await snapshot()).storage['antimatter.form-draft.feature-management'], '{ unreadable saved bytes');
      await click('Reset saved draft'); await click('Cancel');
      assert.equal((await snapshot()).storage['antimatter.form-draft.feature-management'], '{ unreadable saved bytes');
      await click('Reset saved draft'); await click('Reset saved draft'); assert.deepEqual(await run('settingsSmoke.draftBlockers()'), []);
      await click('Application'); await change('Application ID', 'existing'); await call('storageFailure(true)'); await change('Application name', 'New app');
      assert.match((await snapshot()).text, /Could not save the draft/);
      current = await snapshot(); assert.equal(current.form['Application ID'].disabled, false); assert.equal(current.saveDisabled, true);
      await change('Application ID', 'new-app');
      await call("page('other')"); await call("page('features')");
      assert.equal((await snapshot()).form['Application ID'].value, 'new-app');
      assert.ok((await run('settingsSmoke.draftBlockers()')).length);
      await call('storageFailure(false)'); await click('Retry draft storage'); assert.deepEqual(await run('settingsSmoke.draftBlockers()'), []);
      await window.reload(); await tick(); await call("page('features')");
      assert.equal((await snapshot()).form['Application name'].value, 'New app');
      await click('Save');
      assert.equal((await snapshot()).features.applications[1].name, 'New app');
      assert.equal(Object.keys((await snapshot()).storage).some(key => key.endsWith('feature-management')), false);
      await click('Rename'); current = await snapshot(); assert.equal(current.form['Application ID'].disabled, true);
      await change('Application name', 'Renamed app'); await click('Save'); assert.equal((await snapshot()).features.applications[1].name, 'Renamed app');
      await click('Feature'); await change('Feature key', 'preview'); await change('Feature description', 'Preview the project'); await toggle('On by default'); await click('Save');
      current = await snapshot(); assert.equal(current.features.applications[1].features[0].enabled, true);
      await change('Override preview', 'false'); assert.equal((await snapshot()).features.applications[1].features[0].enabled, false);
      await change('Override preview', 'true'); assert.equal((await snapshot()).features.applications[1].features[0].enabled, true);
      await change('Override preview', 'default'); assert.equal((await snapshot()).features.applications[1].features[0].override, null);
      await click('Feature'); await change('Feature key', 'preview');
      current = await snapshot(); assert.equal(current.form['Feature key'].disabled, false); assert.equal(current.saveDisabled, true); await click('Discard draft');
      await change('Application', 'existing'); await click('Edit'); await change('Feature description', 'My replacement description');
      assert.equal((await snapshot()).form['Feature key'].disabled, true);
      await call('featureConflict()');
      await call("page('other')"); await call("page('features')");
      current = await snapshot(); assert.equal(current.saveDisabled, true);
      assert.equal(current.form['Feature description'].value, 'My replacement description'); assert.match(current.text, /SDK changed this description/);
      await click('Keep my changes'); await click('Save'); assert.equal((await snapshot()).features.applications[0].features[0].description, 'My replacement description');
      await toggle('Enable local SDK'); assert.equal((await snapshot()).features.api.endpoint, '/fixture/sdk.sock');
      await screenshot('features-desktop.png');
      await click('Feature'); await change('Feature key', 'unsaved'); await click('Done'); await click('Cancel');
      assert.equal((await snapshot()).form['Feature key'].value, 'unsaved'); await click('Discard draft');
      await change('Application', 'new-app'); await click('Remove preview'); await click('Remove');
      assert.equal((await snapshot()).features.applications[1].features.length, 0);
      await click('Remove'); await click('Remove'); assert.equal((await snapshot()).features.applications.length, 1);
      await click('Feature'); await change('Feature key', 'survives-restart'); await change('Feature description', 'Keep this draft');
      const featureDraftBeforeRestart = (await snapshot()).storage['antimatter.form-draft.feature-management'];
      await window.reload(); await tick(); await call("page('features')");
      current = await snapshot(); assert.equal(current.form['Feature key'].value, 'survives-restart');
      assert.equal(current.form['Feature description'].value, 'Keep this draft');
      assert.equal(current.storage['antimatter.form-draft.feature-management'], featureDraftBeforeRestart);
      await click('Done'); await click('Discard edits');
      assert.equal(Object.keys((await snapshot()).storage).some(key => key.endsWith('feature-management')), false);
      await call("page('features')"); assert.equal((await snapshot()).form['Feature key'], undefined);
      window.setSize(440, 780); await tick();
      assert.ok(await run('document.documentElement.scrollWidth <= innerWidth'));
      await screenshot('features-narrow.png'); await call("page('memory')"); await click('Add entry');
      await change('Entry title', 'Narrow draft'); await change('Entry content', 'Project memory');
      assert.ok(await run('document.documentElement.scrollWidth <= innerWidth'));
      await screenshot('memory-library-narrow.png');
      assert.deepEqual(failures, []);
      console.log('Settings smoke passed: memory CRUD/toggles/read-only content, workspace/section/restart draft recovery, explicit conflict and discard; feature create/rename/duplicate validation, application+flag navigation/restart draft recovery, flags/defaults/overrides/SDK conflicts, removal, close confirmation and narrow layout; visible quota/removal errors, restart blockers, retry, and corrupt saved-byte preservation/reset.');
      window.destroy(); app.exit(0);
    } catch (error) {
      console.error(error, failures);
      await fs.writeFile(path.join(output, 'failure.png'), (await window.webContents.capturePage()).toPNG());
      window.destroy(); app.exit(1);
    }
  }).catch((error) => { console.error(error); app.exit(1); });
}
